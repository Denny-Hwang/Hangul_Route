import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import {
  AddedInSchema,
  CATALOG,
  CATALOG_QUEST_ADDITIONS,
  CATALOG_VERSION,
  CatalogSchema,
  LAST_HAND_KEPT_CATALOG_VERSION,
  LessonCellSchema,
  StoryObjectSchema,
  questIdsAtVersion,
  type Catalog,
  type CatalogCell,
  type CatalogQuest,
} from '..';
import { assembleCatalog, type CatalogSources, type GeneratedStoryRow } from '../catalog/assemble';
import { GENERATED_CATALOG_VERSION, GENERATED_QUEST_ADDITIONS } from '../catalog/catalog.generated';
import CATALOG_V32_JSON from './fixtures/catalog-v32.json';

/**
 * F-CURR-002 §9.1 (row CM-6): the catalogue rows of content/ are generated by
 * scripts/build-lessons.mjs, and CATALOG_VERSION is the largest `addedIn` stamp.
 * `fixtures/catalog-v32.json` is the last hand-kept catalogue (version 32), frozen when
 * CM-6 switched to the generated rows; the switch was row-for-row equal to it.
 */

const V32 = CATALOG_V32_JSON as Catalog;
const CONTENT = join(__dirname, '..', '..', '..', '..', 'content');
const pick = <T extends object, K extends keyof T>(row: T, keys: readonly K[]): Pick<T, K> =>
  Object.fromEntries(keys.map((k) => [k, row[k]])) as Pick<T, K>;

describe('catalogue parity with the last hand-kept catalogue (version 32)', () => {
  it('the frozen catalogue is a valid catalogue of version 32', () => {
    expect(CatalogSchema.safeParse(V32).success).toBe(true);
    expect(V32.version).toBe(LAST_HAND_KEPT_CATALOG_VERSION);
    expect(V32.cells).toHaveLength(35);
  });

  it('keeps every cell in grid order with its id, stage, theme and status, and its quests in order (more may follow)', () => {
    expect(CATALOG.cells.map((c) => c.episodeId).slice(0, V32.cells.length)).toEqual(V32.cells.map((c) => c.episodeId));
    for (const cell of V32.cells) {
      const live = CATALOG.cells.find((c) => c.episodeId === cell.episodeId) as CatalogCell;
      expect(pick(live, ['stage', 'theme', 'episodeId', 'status']), cell.episodeId).toEqual(pick(cell, ['stage', 'theme', 'episodeId', 'status']));
      expect(live.questIds.slice(0, cell.questIds.length), cell.episodeId).toEqual(cell.questIds);
    }
  });

  it('keeps every quest with its cell, stage, theme, kind and what it teaches', () => {
    const keys = ['id', 'episodeId', 'stage', 'theme', 'kind', 'teaches'] as const;
    for (const quest of V32.quests) {
      const live = CATALOG.quests.find((q) => q.id === quest.id) as CatalogQuest;
      expect(live, quest.id).toBeDefined();
      expect(pick(live, keys), quest.id).toEqual(pick(quest, keys));
    }
  });

  it('keeps every story at its shelf order with its quest and anchor, and every topic with its order and free flag', () => {
    for (const story of V32.stories) {
      expect(pick(CATALOG.stories[story.order - 1], ['id', 'questId', 'order', 'anchor']), story.id).toEqual(pick(story, ['id', 'questId', 'order', 'anchor']));
    }
    for (const topic of V32.topics) {
      expect(pick(CATALOG.topics.find((t) => t.key === topic.key) ?? topic, ['id', 'order', 'free']), topic.key).toEqual(pick(topic, ['id', 'order', 'free']));
    }
  });

  it('orders the lesson quests by route (cell by cell), then the story quests in shelf order', () => {
    const lessons = CATALOG.quests.filter((q) => q.kind === 'lesson').map((q) => q.id);
    expect(lessons).toEqual(CATALOG.cells.flatMap((c) => c.questIds));
    expect(CATALOG.quests.filter((q) => q.kind === 'story').map((q) => q.id)).toEqual(CATALOG.stories.map((s) => s.questId));
  });
});

describe('CATALOG_VERSION from addedIn stamps', () => {
  it('is the largest stamp, or 32 when no shipped quest carries one', () => {
    const stamps = Object.keys(GENERATED_QUEST_ADDITIONS).map(Number);
    expect(CATALOG_VERSION).toBe(GENERATED_CATALOG_VERSION);
    expect(CATALOG_VERSION).toBe(Math.max(LAST_HAND_KEPT_CATALOG_VERSION, ...stamps));
  });

  it('keeps the hand-kept history up to 32 and appends each stamp after it', () => {
    const versions = Object.keys(CATALOG_QUEST_ADDITIONS).map(Number);
    expect(versions.filter((v) => v <= LAST_HAND_KEPT_CATALOG_VERSION)).toEqual(Array.from({ length: 24 }, (_, i) => i + 9));
    for (const v of versions.filter((x) => x > LAST_HAND_KEPT_CATALOG_VERSION)) {
      expect(AddedInSchema.safeParse(v).success, `version ${v} is a date stamp`).toBe(true);
      expect(CATALOG_QUEST_ADDITIONS[v]).toEqual(GENERATED_QUEST_ADDITIONS[v]);
    }
  });

  it('lists every shipped quest under some version, so a stored placement knows what it skipped', () => {
    expect([...questIdsAtVersion(CATALOG_VERSION)].sort()).toEqual(CATALOG.quests.map((q) => q.id).sort());
  });

  it('a stamp is a real calendar date YYYYMMDD, larger than every hand-kept version', () => {
    for (const ok of [20260101, 20261105, 20280229, 20991231]) expect(AddedInSchema.safeParse(ok).success, String(ok)).toBe(true);
    for (const bad of [32, 2026110, 20251231, 20261332, 20260230, 20270229, 20261105.5, 210001011]) {
      expect(AddedInSchema.safeParse(bad).success, String(bad)).toBe(false);
    }
  });

  it('a lesson quest and a story carry their stamp in their own content file; a bad stamp fails the schema', () => {
    const cell = JSON.parse(readFileSync(join(CONTENT, 'episodes', 'stage-2', 'letters.json'), 'utf8'));
    const stamped = { ...cell, quests: cell.quests.map((q: object, i: number) => (i === 0 ? { ...q, addedIn: 20261105 } : q)) };
    const parsed = LessonCellSchema.safeParse(stamped);
    expect(parsed.success).toBe(true);
    expect(parsed.data?.quests[0]?.addedIn).toBe(20261105);
    expect(LessonCellSchema.safeParse({ ...stamped, quests: stamped.quests.map((q: object, i: number) => (i === 0 ? { ...q, addedIn: 20261332 } : q)) }).success).toBe(false);
    const tale = JSON.parse(readFileSync(join(CONTENT, 'stories', 'hangeul-day.json'), 'utf8'));
    expect(StoryObjectSchema.safeParse({ ...tale, addedIn: 20261105 }).success).toBe(true);
    expect(StoryObjectSchema.safeParse({ ...tale, addedIn: '2026-11-05' }).success).toBe(false);
  });
});

/** A small catalogue to assemble: two cells out of order, a story off the shelf list, three topics. */
const lessonCell = (stage: CatalogCell['stage'], theme: CatalogCell['theme'], questIds: string[]): CatalogCell => ({
  stage,
  theme,
  episodeId: `episode:${stage}-${theme}`,
  title: `${stage} ${theme}`,
  status: 'shipped',
  minutes: 10,
  questIds,
});
const lessonQuest = (id: string, cell: CatalogCell): CatalogQuest => ({
  id,
  episodeId: cell.episodeId,
  stage: cell.stage,
  theme: cell.theme,
  title: id,
  minutes: 5,
  teaches: [],
  kind: 'lesson',
});
const story = (slug: string, stage = 1): GeneratedStoryRow => ({ slug, title: slug, recommendedStage: stage, theme: 'letters', minutes: 4, sampler: false, status: 'ready' });
const crafts = lessonCell('stage2', 'crafts', ['quest:c1']);
const letters = lessonCell('stage2', 'letters', ['quest:l1', 'quest:l2']);
const sources = (over: Partial<CatalogSources> = {}): CatalogSources => ({
  version: 32,
  cells: [crafts, letters],
  lessonQuests: [lessonQuest('quest:c1', crafts), lessonQuest('quest:l2', letters), lessonQuest('quest:l1', letters)],
  stories: [story('zeta'), story('alpha', 2), story('hangeul-day')],
  storyShelf: [['hangeul-day', 'hangeul-day'], ['zeta']],
  topics: [
    { id: 'topic:colors', key: 'colors', title: 'Colors', order: 3 },
    { id: 'topic:food', key: 'food', title: 'Food', order: 1 },
    { id: 'topic:animals', key: 'animals', title: 'Animals', order: 2 },
  ],
  freeTopics: 2,
  topicMinutes: 5,
  ...over,
});

describe('assembleCatalog', () => {
  it('puts the cells in grid order and each cell\'s quests in cell order, whatever the input order', () => {
    const catalog = assembleCatalog(sources());
    expect(catalog.cells.map((c) => c.episodeId)).toEqual(['episode:stage2-letters', 'episode:stage2-crafts']);
    expect(catalog.quests.filter((q) => q.kind === 'lesson').map((q) => q.id)).toEqual(['quest:l1', 'quest:l2', 'quest:c1']);
  });

  it('leaves out a quest id no quest row has, and a quest no cell lists', () => {
    const catalog = assembleCatalog(
      sources({ cells: [lessonCell('stage2', 'letters', ['quest:l1', 'quest:gone'])], lessonQuests: [lessonQuest('quest:l1', letters), lessonQuest('quest:stray', letters)] }),
    );
    expect(catalog.quests.filter((q) => q.kind === 'lesson').map((q) => q.id)).toEqual(['quest:l1']);
  });

  it('keeps the frozen shelf order and anchors, and puts a later story after them by slug with no anchor', () => {
    const catalog = assembleCatalog(sources({ stories: [story('zeta'), story('beta'), story('alpha', 2), story('hangeul-day')] }));
    expect(catalog.stories.map((s) => [s.order, s.id, s.anchor])).toEqual([
      [1, 'story:hangeul-day', 'hangeul-day'],
      [2, 'story:zeta', null],
      [3, 'story:alpha', null],
      [4, 'story:beta', null],
    ]);
    expect(catalog.quests.filter((q) => q.kind === 'story').map((q) => [q.id, q.episodeId, q.stage])).toEqual([
      ['quest:story-hangeul-day-listen', 'episode:shelf-hangeul-day', 'stage1'],
      ['quest:story-zeta-listen', 'episode:shelf-zeta', 'stage1'],
      ['quest:story-alpha-listen', 'episode:shelf-alpha', 'stage2'],
      ['quest:story-beta-listen', 'episode:shelf-beta', 'stage1'],
    ]);
  });

  it('orders the topics by their order and frees the first ones', () => {
    const catalog = assembleCatalog(sources());
    expect(catalog.topics.map((t) => [t.key, t.order, t.free, t.minutes, t.questId])).toEqual([
      ['food', 1, true, 5, null],
      ['animals', 2, true, 5, null],
      ['colors', 3, false, 5, null],
    ]);
  });

  it('breaks a tie in topic order by key, and carries the version', () => {
    const catalog = assembleCatalog(
      sources({
        version: 20261105,
        topics: [
          { id: 'topic:food', key: 'food', title: 'Food', order: 1 },
          { id: 'topic:colors', key: 'colors', title: 'Colors', order: 1 },
        ],
      }),
    );
    expect(catalog.topics.map((t) => t.key)).toEqual(['colors', 'food']);
    expect(catalog.version).toBe(20261105);
  });
});
