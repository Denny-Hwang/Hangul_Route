/**
 * Spanish web console and grown-up pages on app.hangulroute.com (F-I18N-001 PR 15). Caregiver surface: never
 * "retrasado", "vago" or a learner-banned word; counts go through `plural('es', …)`, dates and amounts arrive
 * formatted, names arrive as arguments. Neutral international Spanish, "tú", no gendered adjective about a
 * person ("estudiante", "docente" and "adulto" as nouns). No age wording: the console speaks of learners and
 * students, never of "kids".
 */
/** "la licencia de St. Mary's": Spanish puts the school after the noun, so no possessive clash. */
const licenseOf = (school: string): string => `la licencia de ${school}`;
/** A usage count, "{n} de {cap} <sustantivos>" or "{n} <sustantivos>" when there is no cap (null). */
const usageCount =
  (one: string, other: string) =>
  (n: number, cap: number | null): string =>
    cap === null ? plural('es', n, { one: `${n} ${one}`, other: `${n} ${other}` }) : plural('es', cap, { one: `${n} de ${cap} ${one}`, other: `${n} de ${cap} ${other}` });
/** "1 elemento" / "4 elementos": `planCounts.items`, also inside `plan.summary.*`. */
const planItems = (items: number): string => plural('es', items, { one: `${items} elemento`, other: `${items} elementos` });
/** "1 estudiante" / "3 miembros": `planCounts.targets`, also inside `plan.summary.some.*`. */
const planTargets = (kind: 'family' | 'class' | 'school', n: number): string =>
  kind === 'school'
    ? plural('es', n, { one: `${n} miembro`, other: `${n} miembros` })
    : plural('es', n, { one: `${n} estudiante`, other: `${n} estudiantes` });
/** "3 lecciones más se abren con una Licencia de Grupo. Quedan fuera de este plan." (F-ENT-003 section 3.9.3). */
const leftOut = (n: number, product: string): string =>
  plural('es', n, {
    one: `${n} lección más se abre con ${product}. Queda fuera de este plan.`,
    other: `${n} lecciones más se abren con ${product}. Quedan fuera de este plan.`,
  });
const studentsWord = (n: number): string => plural('es', n, { one: 'estudiante', other: 'estudiantes' });

