// ------------------------------------------------------------------------------------------------ tokens.css
function tokensCss() {
  const out = [];
  for (const [group, values] of Object.entries(T.colors)) {
    for (const [key, value] of Object.entries(values)) out.push(`  --colors-${group}-${key}: ${value};`);
  }
  for (const [k, v] of Object.entries(T.spacing)) out.push(`  --spacing-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(T.radii)) out.push(`  --radii-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(T.borderWidth)) out.push(`  --border-width-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(T.touchTarget)) out.push(`  --touch-${k}: ${v}px;`);
  // Type sizes in rem (token / 16), so the board's 200 % text setting enlarges every line, as the OS text size does.
  for (const [k, v] of Object.entries(T.typography.size)) out.push(`  --size-${k}: ${v / 16}rem;`);
  // The same sizes in dp, for large type (title, display, hero), which grows by 1 + (f - 1) / 2 (DisplaySheet spec).
  for (const [k, v] of Object.entries(T.typography.size)) out.push(`  --size-dp-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(T.typography.weight)) out.push(`  --weight-${k}: ${v};`);
  for (const [k, v] of Object.entries(T.typography.leading)) out.push(`  --leading-${k}: ${v};`);
  out.push(`  --max-width-reading: ${T.layout.maxWidth.reading}px;`);
  for (const [k, v] of Object.entries(T.layout.gutter)) out.push(`  --gutter-${k}: ${v}px;`);
  const shadow = (s) => {
    const hex = s.shadowColor.replace('#', '');
    const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16));
    return `${s.shadowOffset.width}px ${s.shadowOffset.height}px ${s.shadowRadius}px rgba(${r}, ${g}, ${b}, ${s.shadowOpacity})`;
  };
  out.push(`  --shadow-card: ${shadow(T.shadows.card)};`);
  out.push(`  --shadow-modal: ${shadow(T.shadows.modal)};`);
  return `/*\n * GENERATED by ../tools/build-mocks.mjs from packages/design-system/src/tokens.ts. Do not edit.\n * One custom property per token, named after it. The only file of this design pass with colour or size values.\n */\n:root {\n${out.join('\n')}\n}\n`;
}

