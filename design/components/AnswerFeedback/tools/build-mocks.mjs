const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** An `Icon` from the design system's glyph data. `color` is a CSS colour expression (a token var). */
function icon(name, size, color, cls = 'icon') {
  const parts = iconGlyphs[name];
  if (!parts) throw new Error(`no glyph ${name}`);
  const paths = parts
    .map((p) =>
      p.kind === 'fill'
        ? `<path d="${p.d}" fill="currentColor"/>`
        : `<path d="${p.d}" fill="none" stroke="currentColor" stroke-width="${p.width ?? 2}" stroke-linecap="round" stroke-linejoin="round"/>`,
    )
    .join('');
  return `<svg class="${cls}" data-icon="${name}" width="${size}" height="${size}" viewBox="0 0 24 24" style="color: ${color}" aria-hidden="true" focusable="false">${paths}</svg>`;
}

