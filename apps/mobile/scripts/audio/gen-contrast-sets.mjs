// Writes src/content/__generated__/contrast-sets.ts from content/audio/contrast-sets.json and the clip lock
// (AMENDMENTS-MINIMAL-PAIRS section 3.4, row MP-1a). The module lists every contrast set with the clip of each
// member and `approved: boolean`: true only when the set holds an `approval` (the owner's blind listen, MP-3) whose
// `mp3Sha256` names, for every member, the processed MP3 the lock holds now. A clip that changed after the listen, a
// `lapsed` set and a set with no approval are all `approved: false`, and a round of an unapproved set is never played.
//
//   node scripts/audio/gen-contrast-sets.mjs                       write the module
//   node scripts/audio/gen-contrast-sets.mjs --check               exit 1 if the committed module is stale
//   node scripts/audio/gen-contrast-sets.mjs --with-e2e-fixtures   the fixture build: the sets of
//                                                                  e2e/fixtures/audio/contrast-sets.json replace the real ones
//                                                                  of the same id, approved by the sha256 of their fixture clips
//
// Input is the catalogue and tts-lock.json only, never the manifest: the manifest builder imports the game scopes, which
// import this module (build order: catalogue -> this -> manifest -> audio map). `audio:map` (gen-audio-map.mjs) runs it
// first, so `build:web` and the fixture build always carry a current module. A fixture module is never committed; the
// drift test and `--check` fail if it is.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { CONTRAST_SETS_FILE, parseContrastSets } from './content-sources.mjs';
import { LOCK_FILE, VOICE_LOCK_FILE, parseLock, parseVoiceLock } from './tts/lock-lib.mjs';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', '..');

export const CONTRAST_MODULE_FILE = 'src/content/__generated__/contrast-sets.ts';
/** The e2e-only approvals (relative to apps/mobile): sets over fixture clips, read by the fixture build only. */
export const E2E_CONTRAST_FIXTURE_FILE = 'e2e/fixtures/audio/contrast-sets.json';
const E2E_FIXTURE_AUDIO_DIR = 'e2e/fixtures/audio';

const sha256File = (path) => createHash('sha256').update(readFileSync(path)).digest('hex');

/** `ref` -> processed MP3 sha256 of the locked voice (a row whose MP3 is not processed yet has none). */
export function lockShaOf(lock, voiceLock) {
  const shas = new Map();
  for (const row of lock.rows) {
    if (row.engine === voiceLock.engine && row.voice === voiceLock.voice && row.mp3Sha256 !== null) shas.set(row.ref, row.mp3Sha256);
  }
  return (ref) => shas.get(ref);
}

/**
 * Whether a set may be played: it has an `approval`, is not `lapsed`, and `approval.mp3Sha256[ref]` equals `shaOfRef(ref)`
 * for every member (a clip with no sha, or another one, fails the set).
 *
 * @param {{ members: readonly { ref: string }[], approval?: { mp3Sha256: Record<string, string> }, lapsed?: unknown }} set
 * @param {(ref: string) => string | undefined} shaOfRef
 */
export function approvedOf(set, shaOfRef) {
  if (set.approval === undefined || set.lapsed !== undefined) return false;
  return set.members.every((m) => {
    const sha = shaOfRef(m.ref);
    return sha !== undefined && set.approval.mp3Sha256[m.ref] === sha;
  });
}

/** The approvals that no longer match: a set whose approval names a sha the clip no longer has (for the lapse test and message). */
export function staleApprovalsOf(sets, shaOfRef) {
  return sets
    .filter((s) => s.approval !== undefined && s.lapsed === undefined)
    .flatMap((s) => s.members.filter((m) => shaOfRef(m.ref) !== s.approval.mp3Sha256[m.ref]).map((m) => ({ set: s.id, ref: m.ref, approved: s.approval.mp3Sha256[m.ref], now: shaOfRef(m.ref) ?? null })));
}

const HEADER = [
  '// GENERATED by scripts/audio/gen-contrast-sets.mjs (pnpm --filter @hangul-route/mobile audio:map) — do not edit.',
  '// Source: content/audio/contrast-sets.json and content/audio/tts-lock.json (AMENDMENTS-MINIMAL-PAIRS section 3.4).',
  '// `approved` is true only when the owner approved the set by listening AND every member is still the clip that was heard.',
  "export type ContrastKind = 'plain' | 'aspirated' | 'tense';",
  "export type ContrastSeries = 'k' | 't' | 'p' | 'c' | 's';",
  '',
  'export interface ContrastMemberEntry {',
  '  readonly text: string;',
  '  readonly romanization: string;',
  '  readonly en: string;',
  '  readonly ref: string;',
  '  readonly kind: ContrastKind;',
  '}',
  '',
  'export interface ContrastSetEntry {',
  '  readonly id: string;',
  '  readonly series: ContrastSeries;',
  '  /** The game scope that plays the set (`minigame:s1-life-q3-pairs`). */',
  '  readonly unit: string;',
  '  readonly members: readonly ContrastMemberEntry[];',
  '  readonly approved: boolean;',
  '}',
  '',
];

/** The source of the generated module for `sets` (catalogue entries; `approved` is computed here from `shaOfRef`). */
export function renderContrastModule(sets, shaOfRef) {
  if (sets.length === 0) return `${[...HEADER, 'export const CONTRAST_SETS: readonly ContrastSetEntry[] = [];'].join('\n')}\n`;
  const member = (m) => `      { text: ${JSON.stringify(m.text)}, romanization: ${JSON.stringify(m.romanization)}, en: ${JSON.stringify(m.en)}, ref: ${JSON.stringify(m.ref)}, kind: ${JSON.stringify(m.kind)} },`;
  const set = (s) =>
    [
      '  {',
      `    id: ${JSON.stringify(s.id)},`,
      `    series: ${JSON.stringify(s.series)},`,
      `    unit: ${JSON.stringify(s.unit)},`,
      '    members: [',
      ...s.members.map(member),
      '    ],',
      `    approved: ${approvedOf(s, shaOfRef)},`,
      '  },',
    ].join('\n');
  return `${[...HEADER, 'export const CONTRAST_SETS: readonly ContrastSetEntry[] = [', ...sets.map(set), '];'].join('\n')}\n`;
}

/**
 * The module for the committed catalogue, or (`withFixtures`) for the fixture build: the fixture file's sets replace (or add
 * to) the catalogue's, and every set is approved by the sha256 of its clips in the fixture build (a fixture clip, else the
 * shipped one), never by the real approvals, so the e2e does not depend on which real sets the owner approved.
 */
export function buildContrastModule({ root = repoRoot, withFixtures = false } = {}) {
  const catalogue = parseContrastSets(JSON.parse(readFileSync(join(root, CONTRAST_SETS_FILE), 'utf8')));
  if (!withFixtures) {
    const lock = parseLock(JSON.parse(readFileSync(join(root, LOCK_FILE), 'utf8')));
    const voiceLock = parseVoiceLock(JSON.parse(readFileSync(join(root, VOICE_LOCK_FILE), 'utf8')));
    return { file: CONTRAST_MODULE_FILE, source: renderContrastModule(catalogue.sets, lockShaOf(lock, voiceLock)) };
  }
  const fixturePath = join(root, 'apps/mobile', E2E_CONTRAST_FIXTURE_FILE);
  const fixtureSets = existsSync(fixturePath) ? parseContrastSets(JSON.parse(readFileSync(fixturePath, 'utf8')), E2E_CONTRAST_FIXTURE_FILE).sets : [];
  const byId = new Map(fixtureSets.map((s) => [s.id, s]));
  // No real approval counts in the fixture build: a real set is unapproved unless the fixture file replaces it.
  const real = catalogue.sets.filter((s) => !byId.has(s.id)).map(({ approval: _a, lapsed: _l, ...rest }) => rest);
  const fixtureClip = (ref) => {
    const rel = ref.replace(/^audio\//, '');
    const fixture = join(root, 'apps/mobile', E2E_FIXTURE_AUDIO_DIR, rel);
    if (existsSync(fixture)) return sha256File(fixture);
    const shipped = join(root, 'apps/mobile/assets/audio', rel);
    return existsSync(shipped) ? sha256File(shipped) : undefined;
  };
  return { file: CONTRAST_MODULE_FILE, source: renderContrastModule([...real, ...fixtureSets], fixtureClip) };
}

/**
 * Writes the module, or with `check` compares it: returns { ok, wrote, file, stale }. Used by gen-audio-map.mjs (first
 * thing it does) and by this script's own command line.
 */
export function runContrastSets({ check = false, withFixtures = false, root = repoRoot, out = join(root, 'apps/mobile') } = {}) {
  const { file, source } = buildContrastModule({ root, withFixtures });
  const target = join(out, file);
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (check) return { ok: current === source, wrote: false, file, stale: current !== source };
  mkdirSync(dirname(target), { recursive: true });
  if (current !== source) writeFileSync(target, source);
  return { ok: true, wrote: current !== source, file, stale: false };
}

function main(argv) {
  const known = new Set(['--check', '--with-e2e-fixtures']);
  const unknown = argv.filter((a) => !known.has(a));
  if (unknown.length > 0) {
    process.stderr.write(`usage: gen-contrast-sets.mjs [--check] [--with-e2e-fixtures] (unknown: ${unknown.join(' ')})\n`);
    return 2;
  }
  const result = runContrastSets({ check: argv.includes('--check'), withFixtures: argv.includes('--with-e2e-fixtures') });
  if (argv.includes('--check')) {
    if (!result.ok) {
      process.stderr.write(`${result.file} is stale: run pnpm --filter @hangul-route/mobile audio:map\n`);
      return 1;
    }
    process.stdout.write('contrast sets up to date\n');
    return 0;
  }
  process.stdout.write(`contrast sets ${result.wrote ? 'wrote' : 'unchanged:'} ${result.file}\n`);
  return 0;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;
if (isMain) process.exitCode = main(process.argv.slice(2));
