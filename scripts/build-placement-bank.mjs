#!/usr/bin/env node
// F-PLC-001 §3.4 — placement question-bank generator (PR P-4).
//
// Reads content/placement/index.json (`{ version, warmup, files }`) and the strand
// files it lists (`{ strand, templates }`, one question per template, English base
// language only) and writes one checked-in module:
//
//   apps/mobile/src/content/placement.generated.ts
//       PLACEMENT_BANK     PlacementBank      { version, templates } in file order
//       PLACEMENT_WARMUP   PlacementTemplate  the unscored warm-up question (not in the bank)
//
// This is a shaper: it checks the JSON it must emit, maps the Korean `prompt` and
// `spoken` objects of a template onto the question fields `promptKo`,
// `promptRomanization` and `spokenKo`, and drops what the app does not need. Semantic
// validation (romanization against the converter, per-strand counts, symbol coverage,
// picture art) is the job of packages/content-schema/src/__tests__/placement-bank.test.ts
// and scripts/validate-content.mjs. The literals are typed by contextual typing, so
// `tsc --noEmit` and `PlacementBankSchema` are further gates.
//
// Why `prompt` / `spoken` objects in the JSON: Hangul may only sit in fields named
// `ko` (F-CNT-001), and each such object must carry a romanization and a gloss.
// The gloss of a prompt is a review aid and is not emitted.
//
// Usage:
//   node scripts/build-placement-bank.mjs            write the module
//   node scripts/build-placement-bank.mjs --check    fail if the checked-in module differs (CI)
//
// Dependency-free Node (same family as build-vocab.mjs). Exit 0 when written / in sync,
// 1 on a content or drift error, 2 on a usage error. HANGUL_ROUTE_ROOT overrides the
// repo root (tests).

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const GENERATED_HEADER =
  "// GENERATED by scripts/build-placement-bank.mjs — do not edit. Source: content/placement/*.json\n";

class ContentError extends Error {
  constructor(message, file) {
    super(message);
    this.file = file;
  }
}

const TEMPLATE_ID = /^pitem:[a-z0-9-]+$/;

// ---- shaping (pure) --------------------------------------------------------------

function isObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function str(obj, field, where) {
  const value = obj[field];
  if (typeof value !== "string" || value.length === 0) {
    throw new ContentError(`${where}: ${field} must be a non-empty string`);
  }
  return value;
}

function optStr(obj, field, where) {
  const value = obj[field];
  if (value === undefined) return undefined;
  if (typeof value !== "string") throw new ContentError(`${where}: ${field} must be a string`);
  return value;
}

function bool(obj, field, where) {
  if (typeof obj[field] !== "boolean") throw new ContentError(`${where}: ${field} must be a boolean`);
  return obj[field];
}

function strings(value, field, where) {
  if (!Array.isArray(value) || value.some((v) => typeof v !== "string")) {
    throw new ContentError(`${where}: ${field} must be an array of strings`);
  }
  return value;
}

/** A Korean text object of the source: `ko`, `romanization` and a gloss (the gloss is not emitted). */
function koText(value, field, where) {
  if (!isObject(value)) throw new ContentError(`${where}: ${field} must be an object`);
  for (const key of ["ko", "romanization", "en"]) {
    if (typeof value[key] !== "string" || value[key].length === 0) {
      throw new ContentError(`${where}: ${field}.${key} must be a non-empty string`);
    }
  }
  return { ko: value.ko, romanization: value.romanization };
}

function shapeOption(option, where) {
  if (!isObject(option)) throw new ContentError(`${where}: an option must be an object`);
  const at = `${where} option ${typeof option.id === "string" ? option.id : "(without id)"}`;
  const out = { id: str(option, "id", at) };
  for (const field of ["ko", "romanization", "en", "pictureRef", "sound"]) {
    const value = optStr(option, field, at);
    if (value !== undefined) out[field] = value;
  }
  out.isCorrect = bool(option, "isCorrect", at);
  return out;
}

function shapeRequires(requires, where) {
  if (!isObject(requires)) throw new ContentError(`${where}: requires must be an object`);
  if (typeof requires.audio !== "boolean") throw new ContentError(`${where}: requires.audio must be a boolean`);
  if (requires.picture !== null && requires.picture !== "card" && requires.picture !== "word") {
    throw new ContentError(`${where}: requires.picture must be null, card or word`);
  }
  return { audio: requires.audio, picture: requires.picture };
}

function shapeQuestion(q, where) {
  if (!isObject(q)) throw new ContentError(`${where}: question must be an object`);
  const prompt = q.prompt === undefined ? undefined : koText(q.prompt, "prompt", where);
  const spoken = q.spoken === undefined ? undefined : koText(q.spoken, "spoken", where);
  if (!Array.isArray(q.options) || q.options.length === 0) {
    throw new ContentError(`${where}: options must be a non-empty array`);
  }
  const out = { format: str(q, "format", where) };
  if (prompt) out.promptKo = prompt.ko;
  const promptRomanization = prompt?.romanization ?? spoken?.romanization;
  if (promptRomanization !== undefined) out.promptRomanization = promptRomanization;
  if (spoken) out.spokenKo = spoken.ko;
  out.options = q.options.map((o) => shapeOption(o, where));
  out.tags = strings(q.tags, "tags", where);
  out.requires = shapeRequires(q.requires, where);
  out.leaks = bool(q, "leaks", where);
  return out;
}

/** One source template to the bank's template. `fileStrand` is the strand of its file. */
export function shapeTemplate(template, where, fileStrand) {
  if (!isObject(template)) throw new ContentError(`${where}: a template must be an object`);
  const id = str(template, "id", where);
  if (!TEMPLATE_ID.test(id)) throw new ContentError(`${where}: id must match pitem:[a-z0-9-]+ (got ${id})`);
  const at = id;
  const strand = str(template, "strand", at);
  if (fileStrand !== undefined && strand !== fileStrand) {
    throw new ContentError(`${at}: strand ${strand} is not the strand ${fileStrand} of its file`);
  }
  const status = str(template, "status", at);
  if (status !== "draft" && status !== "ready") throw new ContentError(`${at}: status must be draft or ready`);
  const out = {
    id,
    strand,
    gate: str(template, "gate", at),
    form: str(template, "form", at),
    question: shapeQuestion(template.question, at),
    glossEn: str(template, "glossEn", at),
    status,
  };
  for (const field of ["reviewedBy", "reviewedAt"]) {
    const value = optStr(template, field, at);
    if (value !== undefined) out[field] = value;
  }
  if (template.incompatibleWith !== undefined) out.incompatibleWith = strings(template.incompatibleWith, "incompatibleWith", at);
  return out;
}

function checkIndex(index) {
  if (!isObject(index)) throw new ContentError("index.json must hold one JSON object");
  if (!Number.isInteger(index.version) || index.version < 1) {
    throw new ContentError("index.json: version must be a positive integer");
  }
  if (typeof index.warmup !== "string" || !TEMPLATE_ID.test(index.warmup)) {
    throw new ContentError("index.json: warmup must be a pitem id");
  }
  if (!Array.isArray(index.files) || index.files.length === 0) {
    throw new ContentError("index.json: files must be a non-empty list");
  }
  if (index.files.some((f) => typeof f !== "string" || !f.endsWith(".json") || f.includes("/") || f === "index.json")) {
    throw new ContentError("index.json: files must be a non-empty list of .json names");
  }
  const seen = new Set();
  for (const f of index.files) {
    if (seen.has(f)) throw new ContentError(`index.json: ${f} is listed twice`);
    seen.add(f);
  }
}

/**
 * Pure: parsed inputs to the shaped model.
 *   index   parsed index.json
 *   files   { "<name>.json": parsed strand file }
 * Returns { bank: { version, templates }, warmup } (the warm-up is not a bank template).
 */
export function buildPlacementBank({ index, files }) {
  try {
    checkIndex(index);
  } catch (error) {
    error.file = "index.json";
    throw error;
  }
  const templates = [];
  const ids = new Set();
  let warmup;
  for (const name of index.files) {
    const file = files[name];
    if (file === undefined) throw new ContentError(`${name}: listed in index.json but missing`, "index.json");
    try {
      if (!isObject(file)) throw new ContentError(`${name}: must hold one JSON object`);
      const strand = str(file, "strand", name);
      if (!Array.isArray(file.templates)) throw new ContentError(`${name}: templates must be an array`);
      for (const raw of file.templates) {
        const template = shapeTemplate(raw, name, strand);
        if (ids.has(template.id)) throw new ContentError(`${name}: duplicate template id ${template.id}`);
        ids.add(template.id);
        if (template.id === index.warmup) warmup = template;
        else templates.push(template);
      }
    } catch (error) {
      if (error instanceof ContentError && error.file === undefined) error.file = name;
      throw error;
    }
  }
  if (warmup === undefined) throw new ContentError(`index.json: warm-up ${index.warmup} is not in any file`, "index.json");
  return { bank: { version: index.version, templates }, warmup };
}

// ---- rendering --------------------------------------------------------------------

/** A flat object (primitives and arrays of primitives) prints on one line. */
function isLeaf(value) {
  return Object.values(value).every(
    (v) => v === null || typeof v !== "object" || (Array.isArray(v) && v.every((x) => x === null || typeof x !== "object")),
  );
}

function literal(value, indent = "") {
  if (Array.isArray(value)) {
    if (value.every((v) => v === null || typeof v !== "object")) return JSON.stringify(value);
    return `[\n${value.map((v) => `${indent}  ${literal(v, `${indent}  `)}`).join(",\n")}\n${indent}]`;
  }
  if (isObject(value)) {
    if (isLeaf(value)) return JSON.stringify(value);
    const lines = Object.keys(value).map((k) => `${indent}  ${JSON.stringify(k)}: ${literal(value[k], `${indent}  `)}`);
    return `{\n${lines.join(",\n")}\n${indent}}`;
  }
  return JSON.stringify(value);
}

export function renderBank({ bank, warmup }) {
  return (
    GENERATED_HEADER +
    "import type { PlacementBank, PlacementTemplate } from '@hangul-route/content-schema';\n\n" +
    `export const PLACEMENT_BANK: PlacementBank = ${literal(bank)};\n\n` +
    `export const PLACEMENT_WARMUP: PlacementTemplate = ${literal(warmup)};\n`
  );
}

// ---- file system and CLI ---------------------------------------------------------

function relOf(root, file) {
  return relative(root, file).split(sep).join("/");
}

function readJson(root, file) {
  const rel = relOf(root, file);
  if (!existsSync(file)) throw new ContentError(`::error file=${rel}::missing`);
  try {
    return JSON.parse(readFileSync(file, "utf8"));
  } catch (error) {
    throw new ContentError(`::error file=${rel}::not valid JSON: ${error.message}`);
  }
}

/** Reads the tree and shapes it; a shape error is annotated with the file that holds it. */
export function loadModel(root) {
  const dir = join(root, "content", "placement");
  const indexFile = join(dir, "index.json");
  const index = readJson(root, indexFile);
  const files = {};
  const listed = Array.isArray(index?.files) ? index.files : [];
  for (const name of listed) {
    if (typeof name === "string" && existsSync(join(dir, name))) files[name] = readJson(root, join(dir, name));
  }
  try {
    return buildPlacementBank({ index, files });
  } catch (error) {
    if (!(error instanceof ContentError)) throw error;
    // a shape error is annotated with the file that holds it
    throw new ContentError(`::error file=content/placement/${error.file ?? "index.json"}::${error.message}`);
  }
}

function firstDifference(expected, actual) {
  const a = expected.split("\n");
  const b = actual.split("\n");
  const n = Math.max(a.length, b.length);
  for (let i = 0; i < n; i += 1) {
    if (a[i] !== b[i]) {
      return `line ${i + 1}: expected ${JSON.stringify(a[i] ?? "(end of file)")}, found ${JSON.stringify(b[i] ?? "(end of file)")}`;
    }
  }
  return "no difference";
}

const USAGE = "Usage: node scripts/build-placement-bank.mjs [--check]";

export function main(argv, root) {
  let check = false;
  for (const arg of argv) {
    if (arg === "--check") check = true;
    else {
      process.stderr.write(`unknown argument ${arg}\n${USAGE}\n`);
      return 2;
    }
  }

  let model;
  try {
    model = loadModel(root);
  } catch (error) {
    process.stdout.write(`${error instanceof ContentError ? error.message : `::error::${error.message}`}\n`);
    return 1;
  }

  const file = join(root, "apps", "mobile", "src", "content", "placement.generated.ts");
  const source = renderBank(model);
  const rel = relOf(root, file);
  const summary = `${model.bank.templates.length} templates, warm-up ${model.warmup.id}, bank version ${model.bank.version}`;

  if (check) {
    if (!existsSync(file)) {
      process.stdout.write(`::error file=${rel}::generated placement bank is missing; run node scripts/build-placement-bank.mjs\n`);
      return 1;
    }
    const found = readFileSync(file, "utf8");
    if (found !== source) {
      process.stdout.write(
        `::error file=${rel}::generated placement bank is out of date with content/placement (${firstDifference(source, found)}); run node scripts/build-placement-bank.mjs and commit the result\n`,
      );
      return 1;
    }
    process.stdout.write(`placement bank is up to date (${summary})\n`);
    return 0;
  }

  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, source);
  process.stdout.write(`wrote ${rel}: ${summary}\n`);
  return 0;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;
if (isMain) {
  const root = process.env.HANGUL_ROUTE_ROOT
    ? resolve(process.env.HANGUL_ROUTE_ROOT)
    : join(dirname(fileURLToPath(import.meta.url)), "..");
  process.exitCode = main(process.argv.slice(2), root);
}
