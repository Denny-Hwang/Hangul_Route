#!/usr/bin/env node
// F-STORY-001 §3.9 — story bundle generator (PR 1.4).
//
// Reads content/stories/*.json (not recursive: content/stories/research/ is
// provenance, never shipped), drops `state: 'draft'` files, sorts by `id` and
// writes apps/mobile/src/content/stories.generated.ts:
//
//   storiesAll     Story[]    one object literal per ready story
//   storyEpisodes  Episode[]  one shelf episode per story with a `shelf` block
//   storyQuests    Quest[]    its five-step quest (F-STORY-003 §3.1 skeleton)
//
// The literals are typed by contextual typing, so `tsc --noEmit` proves the
// data matches the schema; there is no runtime parse. The zod schema test is
// the content gate, TypeScript is the second.
//
// Usage:
//   node scripts/build-stories.mjs                      write the bundle
//   node scripts/build-stories.mjs --check              fail if the checked-in bundle differs (CI)
//   node scripts/build-stories.mjs --report             print sizes, fail over budget (CI)
//   node scripts/build-stories.mjs --include-drafts --out <path>
//                                                       preview bundle with drafts (never under apps/)
//
// Dependency-free Node (same family as validate-content.mjs). Exit 0 when the
// bundle is written / in sync / within budget, 1 on a content or drift error,
// 2 on a usage error. HANGUL_ROUTE_ROOT overrides the repo root (tests).

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { gzipSync } from "node:zlib";

export const GENERATED_HEADER =
  "// GENERATED by scripts/build-stories.mjs — do not edit. Source: content/stories/*.json\n";

/**
 * Bundle budget (F-STORY-001 §3.9): the launch set of 24 stories. Raising a
 * ceiling is a reviewed one-line change.
 */
export const BUDGET = Object.freeze({
  totalRaw: 1_000_000,
  totalGzip: 260_000,
  perStoryRaw: 60_000,
});

// Quest copy owned by the generator (F-STORY-001 §3.9). The twin in
// apps/mobile/src/content/story-skeleton.ts (F-STORY-005) must match.
const QUEST_COPY = Object.freeze({
  intro: "Story time",
  read: "Read the story",
  check: "A few questions",
  seq: "Put the story in order",
  reward: "Well done",
});
const STEP_SECONDS = Object.freeze({ intro: 8, read: 150, check: 60, seq: 45, reward: 8 });

const LEVEL_CODES = Object.freeze({ listen: "listen", "read-along": "along", read: "read" });
const STORY_ID_RE = /^story:[a-z0-9]+(-[a-z0-9]+)*$/;
const STATES = new Set(["draft", "ready"]);

export function slugOf(storyId) {
  if (typeof storyId !== "string" || !STORY_ID_RE.test(storyId)) {
    throw new Error(`not a story id (story:<slug>): ${JSON.stringify(storyId)}`);
  }
  return storyId.slice("story:".length);
}

export function levelCode(level) {
  const code = LEVEL_CODES[level];
  if (!code) throw new Error(`unknown story level: ${JSON.stringify(level)}`);
  return code;
}

/** The tier a shelf quest plays: `listen` (F-STORY-004 §3.1), else the first tier. */
function shelfTier(story) {
  const tiers = Array.isArray(story.tiers) ? story.tiers : [];
  const tier = tiers.find((t) => t.level === "listen") ?? tiers[0];
  if (!tier) throw new Error(`${story.id}: a shelf story needs at least one tier`);
  return tier;
}

function need(story, field) {
  const value = story[field];
  if (typeof value !== "string" || value.length === 0) {
    throw new Error(`${story.id}: a story with a shelf block needs ${field}`);
  }
  return value;
}

/** F-STORY-001 §3.9 "Shelf episodes and quests are derived, not hand-written". */
function deriveShelf(story) {
  const slug = slugOf(story.id);
  const code = levelCode(shelfTier(story).level);
  const hoyaIntroEn = need(story, "hoyaIntroEn");
  const hoyaOutroEn = need(story, "hoyaOutroEn");
  const questId = `quest:story-${slug}-${code}`;
  const minutes = Math.max(3, story.minutes);
  const listenCard = story.rewardCardIds?.listen;
  const ref = (step) => `minigame:story-${step}-${code}-${slug}`;

  const episode = {
    id: `episode:shelf-${slug}`,
    stage: "stage1",
    theme: story.theme,
    order: 100 + story.shelf.order,
    titleEn: story.title.en,
    hoyaIntroEn,
    questIds: [questId],
    rewardCardIds: listenCard ? [listenCard] : [],
    estimatedMinutes: minutes,
    status: "ready",
    format: "story",
    placement: "shelf",
    // F-STORY-005 §3.2: the plan catalogue groups episodes without loading stories.
    // The defaults are the schema's (CatalogueFieldsSchema), for a file that omits them.
    pillarTags: Array.isArray(story.pillarTags) ? [...story.pillarTags] : [],
    companionId: story.companionId ?? "hoya",
  };

  const quest = {
    id: questId,
    titleEn: story.title.en,
    estimatedMinutes: minutes,
    steps: [
      { id: "s1", kind: "intro", titleEn: QUEST_COPY.intro, hoyaLineEn: hoyaIntroEn, durationSeconds: STEP_SECONDS.intro },
      {
        id: "s2",
        kind: "present",
        titleEn: QUEST_COPY.read,
        minigameKind: "story-read",
        minigameRef: ref("read"),
        durationSeconds: STEP_SECONDS.read,
      },
      {
        id: "s3",
        kind: "practice",
        titleEn: QUEST_COPY.check,
        minigameKind: "story-check",
        minigameRef: ref("check"),
        durationSeconds: STEP_SECONDS.check,
      },
      {
        id: "s4",
        kind: "apply",
        titleEn: QUEST_COPY.seq,
        minigameKind: "story-sequence",
        minigameRef: ref("seq"),
        durationSeconds: STEP_SECONDS.seq,
      },
      { id: "s5", kind: "reward", titleEn: QUEST_COPY.reward, hoyaLineEn: hoyaOutroEn, durationSeconds: STEP_SECONDS.reward },
    ],
  };
  if (listenCard) quest.rewardCardId = listenCard;

  return { episode, quest };
}

/**
 * Pure: ready stories (already filtered and sorted by the caller or not) to
 * the three arrays. Sorting by id happens here so every caller gets it.
 */
export function buildBundle(stories) {
  const sorted = [...stories].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  const episodes = [];
  const quests = [];
  for (const story of sorted) {
    if (!story.shelf) continue;
    const { episode, quest } = deriveShelf(story);
    episodes.push(episode);
    quests.push(quest);
  }
  return { stories: sorted, episodes, quests };
}

function literal(value) {
  return JSON.stringify(value, null, 2);
}

export function renderBundle({ stories, episodes, quests }) {
  return (
    GENERATED_HEADER +
    "import type { Episode, Quest, Story } from '@hangul-route/content-schema';\n\n" +
    `export const storiesAll: Story[] = ${literal(stories)};\n\n` +
    `export const storyEpisodes: Episode[] = ${literal(episodes)};\n\n` +
    `export const storyQuests: Quest[] = ${literal(quests)};\n`
  );
}

/** Pure: size problems as human-readable strings (empty = within budget). */
export function checkBudget({ perStory, total }) {
  const problems = [];
  for (const s of perStory) {
    if (s.raw > BUDGET.perStoryRaw) {
      problems.push(`${s.id} is ${s.raw} B raw, over the per-story ceiling of ${BUDGET.perStoryRaw} B`);
    }
  }
  if (total.raw > BUDGET.totalRaw) {
    problems.push(`stories.generated.ts is ${total.raw} B raw, over the ceiling of ${BUDGET.totalRaw} B`);
  }
  if (total.gzip > BUDGET.totalGzip) {
    problems.push(`stories.generated.ts is ${total.gzip} B gzip, over the ceiling of ${BUDGET.totalGzip} B`);
  }
  return problems;
}

function sizes(stories, source) {
  const bytes = (text) => Buffer.byteLength(text, "utf8");
  return {
    perStory: stories.map((s) => {
      const text = literal(s);
      return { id: s.id, raw: bytes(text), gzip: gzipSync(text).length };
    }),
    total: { raw: bytes(source), gzip: gzipSync(source).length },
  };
}

// ---- file system and CLI ------------------------------------------------------

class ContentError extends Error {}

function readStories(root, includeDrafts) {
  const dir = join(root, "content", "stories");
  if (!existsSync(dir)) return [];
  const names = readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith(".json"))
    .map((e) => e.name)
    .sort();
  const seen = new Map();
  const stories = [];
  for (const name of names) {
    const rel = relative(root, join(dir, name)).split(sep).join("/");
    const fail = (message) => new ContentError(`::error file=${rel}::${message}`);
    let story;
    try {
      story = JSON.parse(readFileSync(join(dir, name), "utf8"));
    } catch (error) {
      throw fail(`not valid JSON: ${error.message}`);
    }
    if (story === null || typeof story !== "object" || Array.isArray(story)) {
      throw fail("a story file must hold one JSON object");
    }
    if (typeof story.id !== "string" || !STORY_ID_RE.test(story.id)) {
      throw fail(`id must be a story id (story:<slug>), got ${JSON.stringify(story.id)}`);
    }
    if (name !== `${slugOf(story.id)}.json`) {
      throw fail(`file name must be ${slugOf(story.id)}.json for id ${story.id}`);
    }
    if (!STATES.has(story.state)) {
      throw fail(`state must be draft or ready, got ${JSON.stringify(story.state)}`);
    }
    if (seen.has(story.id)) throw fail(`duplicate id ${story.id} (also in ${seen.get(story.id)})`);
    seen.set(story.id, rel);
    if (story.state === "ready" || includeDrafts) stories.push(story);
  }
  return stories;
}

const USAGE =
  "Usage: node scripts/build-stories.mjs [--check] [--report] [--include-drafts --out <path>] [--out <path>]";

function parseArgs(argv) {
  const opts = { check: false, report: false, includeDrafts: false, out: undefined };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--check") opts.check = true;
    else if (arg === "--report") opts.report = true;
    else if (arg === "--include-drafts") opts.includeDrafts = true;
    else if (arg === "--out") {
      const value = argv[i + 1];
      if (!value || value.startsWith("--")) return { error: "--out needs a path" };
      opts.out = value;
      i += 1;
    } else return { error: `unknown argument ${arg}` };
  }
  return { opts };
}

export function main(argv, root) {
  const parsed = parseArgs(argv);
  if (parsed.error) {
    process.stderr.write(`${parsed.error}\n${USAGE}\n`);
    return 2;
  }
  const { opts } = parsed;
  const defaultTarget = join(root, "apps", "mobile", "src", "content", "stories.generated.ts");

  if (opts.includeDrafts && !opts.out) {
    process.stderr.write(`--include-drafts needs --out <path>: the app bundle never holds drafts\n${USAGE}\n`);
    return 2;
  }
  const target = opts.out ? (isAbsolute(opts.out) ? opts.out : resolve(root, opts.out)) : defaultTarget;
  if (opts.includeDrafts) {
    const underApps = relative(join(root, "apps"), target);
    if (!underApps.startsWith("..") && !isAbsolute(underApps)) {
      process.stderr.write(`--include-drafts must not write under apps/ (got ${opts.out})\n${USAGE}\n`);
      return 2;
    }
  }

  let bundle;
  try {
    bundle = buildBundle(readStories(root, opts.includeDrafts));
  } catch (error) {
    if (error instanceof ContentError) {
      process.stdout.write(`${error.message}\n`);
    } else {
      process.stdout.write(`::error::${error.message}\n`);
    }
    return 1;
  }
  const source = renderBundle(bundle);
  const targetRel = relative(root, target).split(sep).join("/");

  if (opts.report) {
    const report = sizes(bundle.stories, source);
    const n = report.perStory.length;
    process.stdout.write(`Story bundle (${n} ${n === 1 ? "story" : "stories"}):\n`);
    for (const s of report.perStory) {
      process.stdout.write(`  ${s.id}  ${s.raw} B raw  ${s.gzip} B gzip\n`);
    }
    process.stdout.write(`  total  ${report.total.raw} B raw  ${report.total.gzip} B gzip\n`);
    process.stdout.write(
      `Budget: ${BUDGET.totalRaw} B raw, ${BUDGET.totalGzip} B gzip in total, ${BUDGET.perStoryRaw} B raw per story\n`
    );
    const problems = checkBudget(report);
    for (const p of problems) process.stdout.write(`::error file=${targetRel}::${p}\n`);
    return problems.length === 0 ? 0 : 1;
  }

  if (opts.check) {
    if (!existsSync(target)) {
      process.stdout.write(`::error file=${targetRel}::generated story bundle is missing; run node scripts/build-stories.mjs\n`);
      return 1;
    }
    if (readFileSync(target, "utf8") !== source) {
      process.stdout.write(
        `::error file=${targetRel}::generated story bundle is out of date with content/stories; run node scripts/build-stories.mjs and commit the result\n`
      );
      return 1;
    }
    process.stdout.write(`${targetRel} is up to date (${bundle.stories.length} stories)\n`);
    return 0;
  }

  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, source);
  process.stdout.write(
    `wrote ${targetRel}: ${bundle.stories.length} stories, ${bundle.episodes.length} shelf episodes, ${bundle.quests.length} quests\n`
  );
  return 0;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;
if (isMain) {
  const root = process.env.HANGUL_ROUTE_ROOT
    ? resolve(process.env.HANGUL_ROUTE_ROOT)
    : join(dirname(fileURLToPath(import.meta.url)), "..");
  process.exitCode = main(process.argv.slice(2), root);
}
