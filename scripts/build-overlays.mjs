#!/usr/bin/env node
// F-I18N-001 §3.6 — content overlay generator (PR 12).
//
// Merges content/i18n/<locale>/*.json (`{ locale, domain, entries }`, locale es or ko)
// into one generated module (gitignored; `pnpm generate`, F-CURR-002 row CM-6) that both apps read
// through the workspace package:
//
//   packages/content-schema/src/i18n-overlays.generated.ts
//       OVERLAYS   Overlays   { es: { <entity id>: { <field>: text } }, ko: { ... } }
//   served by the `@hangul-route/content-schema/overlays` subpath, never the package barrel
//   (F-I18N-001 §10 open item 2; size budget in packages/content-schema/src/__tests__/overlays-bundle.test.ts).
//
// This is a shaper. It emits only what the app may apply (fields allowed by
// OVERLAY_FIELDS for the id prefix, non-blank strings, well-formed ids), sorted, so a
// bad overlay can never override taught Korean even before CI runs. The language rules
// (unknown ids, Hangul, circular glosses, banned words, missing translations) are
// scripts/validate-content.mjs's job. Folders other than es / ko are skipped here and
// reported there.
//
// Usage:
//   node scripts/build-overlays.mjs            write the module
//   node scripts/build-overlays.mjs --check    determinism (CI): fail if the module an earlier run wrote (pnpm generate, the postinstall) differs from this run; generated, never committed (F-CURR-002 row CM-6)
//
// Dependency-free Node (same family as build-vocab.mjs / build-placement-bank.mjs).
// Exit 0 when written / in sync, 1 on a content or drift error, 2 on a usage error.
// HANGUL_ROUTE_ROOT overrides the repo root (tests).

import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { OVERLAY_LOCALES, isOverlayFieldAllowed } from "./overlay-fields.mjs";
import { writeIfChanged } from "./write-if-changed.mjs";

export const GENERATED_HEADER =
  "// GENERATED by scripts/build-overlays.mjs — do not edit. Source: content/i18n/<locale>/*.json (F-I18N-001 §3.6)\n";

const OUT = join("packages", "content-schema", "src", "i18n-overlays.generated.ts");

class ContentError extends Error {
  constructor(message, file) {
    super(message);
    this.file = file;
  }
}

const isObject = (v) => v !== null && typeof v === "object" && !Array.isArray(v);

/**
 * files: [{ rel: "content/i18n/<locale>/<name>.json", json }] -> { es: {...}, ko: {...} },
 * entity ids and field names sorted. Throws ContentError on a file that is not an
 * overlay of its folder's locale and on an entity that sits in two files of one locale.
 */
export function buildOverlays(files) {
  const merged = Object.fromEntries(OVERLAY_LOCALES.map((l) => [l, new Map()]));
  const owner = new Map();
  for (const { rel, json } of files) {
    const locale = rel.split("/")[2];
    if (!isObject(json)) throw new ContentError("an overlay file is { locale, domain, entries }", rel);
    if (json.locale !== locale) throw new ContentError(`locale ${JSON.stringify(json.locale)} differs from its folder ${locale}`, rel);
    if (!isObject(json.entries)) throw new ContentError("entries must be an object keyed by entity id", rel);
    for (const [id, entry] of Object.entries(json.entries)) {
      if (!isObject(entry)) throw new ContentError(`the entry ${id} must be an object of translated fields`, rel);
      const key = `${locale}\u0000${id}`;
      if (owner.has(key)) throw new ContentError(`${id} is also in ${owner.get(key)}; an entity belongs to one overlay file`, rel);
      owner.set(key, rel);
      const fields = Object.entries(entry)
        .filter(([field, text]) => isOverlayFieldAllowed(id, field) && typeof text === "string" && text.trim() !== "")
        .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
      if (fields.length > 0) merged[locale].set(id, Object.fromEntries(fields));
    }
  }
  return Object.fromEntries(
    OVERLAY_LOCALES.map((l) => [l, Object.fromEntries([...merged[l].entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)))]),
  );
}

export function renderOverlays(model) {
  return (
    GENERATED_HEADER +
    "import type { Overlays } from './schemas/locale-overlay';\n\n" +
    `export const OVERLAYS: Overlays = ${JSON.stringify(model, null, 2)};\n`
  );
}

const relOf = (root, file) => relative(root, file).split(sep).join("/");

/** `lessons-stage<n>-<theme>.json`: a lesson cell's glosses, read by build-lessons.mjs (F-CURR-001 §3.10). */
export const isLessonOverlay = (name) => /^lessons-stage\d-[a-z]+\.json$/.test(name);

function readFiles(root) {
  const dir = join(root, "content", "i18n");
  const files = [];
  for (const locale of OVERLAY_LOCALES) {
    const localeDir = join(dir, locale);
    if (!existsSync(localeDir) || !statSync(localeDir).isDirectory()) continue;
    // Lesson glosses (F-CURR-001 §3.10) are compiled into the lesson modules by build-lessons.mjs, not here.
    for (const name of readdirSync(localeDir).filter((n) => n.endsWith(".json") && !isLessonOverlay(n)).sort()) {
      const full = join(localeDir, name);
      const rel = relOf(root, full);
      let json;
      try {
        json = JSON.parse(readFileSync(full, "utf8"));
      } catch (error) {
        throw new ContentError(`invalid JSON: ${error.message}`, rel);
      }
      files.push({ rel, json });
    }
  }
  return files;
}

function summaryOf(model) {
  return OVERLAY_LOCALES.map((l) => `${l} ${Object.keys(model[l]).length} entit${Object.keys(model[l]).length === 1 ? "y" : "ies"}`).join(", ");
}

const USAGE = "Usage: node scripts/build-overlays.mjs [--check]";

export function main(argv, root) {
  let check = false;
  for (const arg of argv) {
    if (arg === "--check") check = true;
    else {
      process.stderr.write(`unknown argument ${arg}\n${USAGE}\n`);
      return 2;
    }
  }

  let model;
  try {
    model = buildOverlays(readFiles(root));
  } catch (error) {
    if (!(error instanceof ContentError)) throw error;
    process.stdout.write(`::error file=${error.file}::${error.message}\n`);
    return 1;
  }

  const file = join(root, OUT);
  const rel = relOf(root, file);
  const source = renderOverlays(model);

  if (check) {
    if (!existsSync(file)) {
      process.stdout.write(`::error file=${rel}::generated overlays are missing; run node scripts/build-overlays.mjs\n`);
      return 1;
    }
    if (readFileSync(file, "utf8") !== source) {
      process.stdout.write(
        `::error file=${rel}::generated overlays are out of date with content/i18n; run pnpm generate (generators must be deterministic)\n`,
      );
      return 1;
    }
    process.stdout.write(`overlays are up to date (${summaryOf(model)})\n`);
    return 0;
  }

  writeIfChanged(file, source);
  process.stdout.write(`wrote ${rel}: ${summaryOf(model)}\n`);
  return 0;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;
if (isMain) {
  const root = process.env.HANGUL_ROUTE_ROOT
    ? resolve(process.env.HANGUL_ROUTE_ROOT)
    : join(dirname(fileURLToPath(import.meta.url)), "..");
  process.exitCode = main(process.argv.slice(2), root);
}
