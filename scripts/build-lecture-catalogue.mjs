#!/usr/bin/env node
// F-TCH-004 §3.11 — lecture catalogue mirror for the console setup page (PR 10).
//
// The console is a static export with no content bundle, so the lecture setup
// page lists stories and vocabulary topics from a checked-in mirror, ids and
// titles only (the presenter expands the ids against its own bundle):
//
//   apps/web/src/data/lecture-catalogue.generated.ts
//       LECTURE_STORIES       { id, titleEn, minutes }  stories the learner Library would list
//       LECTURE_VOCAB_TOPICS  { id, titleEn, words }    topics that are not draft / preview
//
// A story is listed only when it is `ready` and both language- and
// culture-reviewed (the F-STORY-004 production gate, D14), so the console never
// offers a story the presenter would skip as not ready. Stories come in title
// order, topics in their `order`.
//
// F-PLAN-002's shared catalogue (`CATALOG` in @hangul-route/content-schema) has
// landed and replaced the Stage 1 mirror: quest and episode titles and minutes,
// and vocabulary-topic minutes, now come from it (`apps/web/src/data/catalog.ts`).
// This mirror stays, deliberately, for one thing `CATALOG` cannot express: the
// Library's production gate. `CATALOG` lists all 24 shelf stories and all 12
// topics with a `ready | draft` status and no review fields, so it would offer
// the console stories and topics the presenter skips as not ready (D14). Its
// topic ids are also `topic:<key>`, while the deck names them `vocab-topic:<key>`.
// When `CATALOG` carries the review gate, this script is retired (ids are the
// contract, so no deck changes).
//
// Stories are listed (STORIES_IN_LECTURE, true since F-TCH-004 PR 11) now the
// presenter's story adapter exists (`logic/lecture/sources/story.ts`, the same
// review gate), so a chosen story is never skipped as not ready. Story files
// are read and shaped either way, so a broken story file fails here.
//
// It also writes the console's content titles in the other UI languages
// (owner report 2026-10-16, AMENDMENTS-LECTURE-V2 row LV-3: the console showed
// English lesson titles in the es and ko UI, against CLAUDE.md section 1):
//
//   apps/web/src/data/catalogue-titles.generated.ts
//       CATALOGUE_TITLES      { <locale>: { <id>: title } }  grid episode, quest,
//                             story and vocab-topic titles from content/i18n/<locale>/*.json
//
// The console is a static export with no content bundle and must not ship the
// whole overlay set, so only the `title` field of those four id kinds is kept;
// `catalogTitle` (apps/web/src/data/catalog.ts) falls back to CATALOG's English.
//
// Usage:
//   node scripts/build-lecture-catalogue.mjs            write the modules
//   node scripts/build-lecture-catalogue.mjs --check    fail if a checked-in module differs (CI)
//
// Dependency-free Node (same family as build-vocab.mjs). Exit 0 when written / in
// sync, 1 on a content or drift error, 2 on a usage error. HANGUL_ROUTE_ROOT
// overrides the repo root (tests).

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const GENERATED_HEADER =
  "// GENERATED by scripts/build-lecture-catalogue.mjs — do not edit. Source: content/stories/*.json, content/vocab/*.json\n";

export const OUTPUT_REL = ["apps", "web", "src", "data", "lecture-catalogue.generated.ts"];

export const TITLES_HEADER =
  "// GENERATED by scripts/build-lecture-catalogue.mjs — do not edit. Source: content/i18n/<locale>/*.json (the title field)\n";

export const TITLES_REL = ["apps", "web", "src", "data", "catalogue-titles.generated.ts"];

/** The content ids whose titles the console draws: grid episodes (cells), quests, stories and word topics. */
export const TITLE_ID_RE = /^(episode:stage[1-7]-[a-z]+|(quest|story|vocab-topic):[a-z0-9]+(-[a-z0-9]+)*)$/;

/** On since F-TCH-004 PR 11 added the presenter's story adapter. */
export const STORIES_IN_LECTURE = true;

const LISTED_TOPIC_STATUS = new Set(["ready", "shipped"]);

class ContentError extends Error {}

function isObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function str(obj, field, where) {
  const value = obj?.[field];
  if (typeof value !== "string" || value.length === 0) throw new ContentError(`${where}: ${field} must be a non-empty string`);
  return value;
}

function num(obj, field, where) {
  const value = obj?.[field];
  if (typeof value !== "number" || !Number.isInteger(value)) throw new ContentError(`${where}: ${field} must be an integer`);
  return value;
}

// ---- shaping (pure) --------------------------------------------------------------

/** The F-STORY-004 production gate: ready, native-reviewed and culture-reviewed. */
export function isListedStory(story) {
  return story.state === "ready" && story.review?.language === "native-reviewed" && story.review?.culture === "culture-reviewed";
}

export function buildCatalogue({ stories, topicFiles, storiesInLecture = STORIES_IN_LECTURE }) {
  const listedStories = [];
  for (const { name, json } of stories) {
    if (!isObject(json)) throw new ContentError(`${name}: a story file must hold one JSON object`);
    const id = str(json, "id", name);
    const titleEn = str(json.title, "en", `${name}: title`);
    const minutes = num(json, "minutes", name);
    if (storiesInLecture && isListedStory(json)) listedStories.push({ id, titleEn, minutes });
  }
  listedStories.sort((a, b) => a.titleEn.localeCompare(b.titleEn, "en") || a.id.localeCompare(b.id));

  const topics = [];
  for (const { name, json } of topicFiles) {
    if (!isObject(json) || !isObject(json.topic)) throw new ContentError(`${name}: a topic file needs a topic object`);
    if (!Array.isArray(json.items)) throw new ContentError(`${name}: items must be an array`);
    const where = `${name}: topic`;
    const entry = { id: str(json.topic, "id", where), titleEn: str(json.topic, "titleEn", where), words: json.items.length };
    const order = num(json.topic, "order", where);
    if (LISTED_TOPIC_STATUS.has(str(json.topic, "status", where))) topics.push({ order, entry });
  }
  topics.sort((a, b) => a.order - b.order || a.entry.id.localeCompare(b.entry.id));
  return { stories: listedStories, topics: topics.map((t) => t.entry) };
}

export function renderCatalogue(model) {
  return [
    GENERATED_HEADER,
    "/** A story the learner Library would list (F-TCH-004 §3.11): ids and titles only. */",
    "export interface LectureCatalogueStory {",
    "  id: string;",
    "  titleEn: string;",
    "  minutes: number;",
    "}",
    "",
    "/** A vocabulary topic that is not draft or preview. */",
    "export interface LectureCatalogueTopic {",
    "  id: string;",
    "  titleEn: string;",
    "  words: number;",
    "}",
    "",
    `export const LECTURE_STORIES: readonly LectureCatalogueStory[] = ${JSON.stringify(model.stories, null, 2)};`,
    "",
    `export const LECTURE_VOCAB_TOPICS: readonly LectureCatalogueTopic[] = ${JSON.stringify(model.topics, null, 2)};`,
    "",
  ].join("\n");
}

/**
 * The `title` of every grid episode, quest, story and word-topic entry of each overlay
 * locale, sorted by id. A file that is not `{ entries: { <id>: { ... } } }`, or a
 * title that is not a non-empty string, fails the build; other ids and fields are
 * left out (they are not drawn by the console).
 */
export function buildTitles({ overlayFiles }) {
  const byLocale = new Map();
  for (const { locale, name, json } of overlayFiles) {
    if (!isObject(json) || !isObject(json.entries)) throw new ContentError(`${name}: an overlay file needs an entries object`);
    const titles = byLocale.get(locale) ?? new Map();
    byLocale.set(locale, titles);
    for (const [id, entry] of Object.entries(json.entries)) {
      if (!TITLE_ID_RE.test(id) || !isObject(entry) || !("title" in entry)) continue;
      if (typeof entry.title !== "string" || entry.title.trim().length === 0) throw new ContentError(`${name}: ${id}: title must be a non-empty string`);
      if (titles.has(id) && titles.get(id) !== entry.title) throw new ContentError(`${name}: ${id}: a second, different title in ${locale}`);
      titles.set(id, entry.title);
    }
  }
  const out = {};
  for (const locale of [...byLocale.keys()].sort()) {
    const titles = byLocale.get(locale);
    out[locale] = Object.fromEntries([...titles.keys()].sort().map((id) => [id, titles.get(id)]));
  }
  return out;
}

export function renderTitles(titles) {
  return [
    TITLES_HEADER,
    "/**",
    " * Content titles in the UI languages other than English (F-I18N-001 section 3.6), by",
    " * catalogue id: grid episodes, quests, stories and word topics (`vocab-topic:<key>`). Read",
    " * through `catalogTitle` in `catalog.ts`, which falls back to CATALOG's English title.",
    " */",
    `export const CATALOGUE_TITLES: Readonly<Record<string, Readonly<Record<string, string>>>> = ${JSON.stringify(titles, null, 2)};`,
    "",
  ].join("\n");
}

// ---- file system and CLI ---------------------------------------------------------

function relOf(root, file) {
  return relative(root, file).split(sep).join("/");
}

function readDir(root, rel, accept) {
  const dir = join(root, ...rel);
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith(".json") && accept(e.name))
    .map((e) => e.name)
    .sort()
    .map((name) => {
      const file = join(dir, name);
      try {
        return { name: relOf(root, file), json: JSON.parse(readFileSync(file, "utf8")) };
      } catch (error) {
        throw new ContentError(`${relOf(root, file)}: not valid JSON: ${error.message}`);
      }
    });
}

/** Every `content/i18n/<locale>/*.json` file, the locale from its folder. */
function readOverlays(root) {
  const dir = join(root, "content", "i18n");
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort()
    .flatMap((locale) => readDir(root, ["content", "i18n", locale], () => true).map((file) => ({ locale, ...file })));
}

const USAGE = "Usage: node scripts/build-lecture-catalogue.mjs [--check]";

export function main(argv, root) {
  let check = false;
  for (const arg of argv) {
    if (arg === "--check") check = true;
    else {
      process.stderr.write(`unknown argument ${arg}\n${USAGE}\n`);
      return 2;
    }
  }

  let outputs;
  let summary;
  try {
    const model = buildCatalogue({
      stories: readDir(root, ["content", "stories"], () => true),
      topicFiles: readDir(root, ["content", "vocab"], (name) => !name.startsWith("_")),
    });
    const titles = buildTitles({ overlayFiles: readOverlays(root) });
    outputs = [
      { rel: OUTPUT_REL, source: renderCatalogue(model), what: "lecture catalogue", from: "content/stories and content/vocab" },
      { rel: TITLES_REL, source: renderTitles(titles), what: "catalogue titles", from: "content/i18n" },
    ];
    const counts = Object.entries(titles).map(([locale, map]) => `${locale} ${Object.keys(map).length}`);
    summary = `${model.stories.length} stories, ${model.topics.length} vocabulary topics, titles: ${counts.length > 0 ? counts.join(", ") : "none"}`;
  } catch (error) {
    process.stdout.write(`::error::${error.message}\n`);
    return 1;
  }

  if (check) {
    let ok = true;
    for (const { rel: parts, source, what, from } of outputs) {
      const file = join(root, ...parts);
      const rel = relOf(root, file);
      if (!existsSync(file)) {
        process.stdout.write(`::error file=${rel}::${what} is missing; run node scripts/build-lecture-catalogue.mjs\n`);
        ok = false;
      } else if (readFileSync(file, "utf8") !== source) {
        process.stdout.write(`::error file=${rel}::${what} is out of date with ${from}; run node scripts/build-lecture-catalogue.mjs and commit the result\n`);
        ok = false;
      }
    }
    if (!ok) return 1;
    process.stdout.write(`lecture catalogue and titles are up to date (${summary})\n`);
    return 0;
  }

  for (const { rel: parts, source } of outputs) {
    const file = join(root, ...parts);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, source);
  }
  process.stdout.write(`wrote ${outputs.map((o) => o.rel.join("/")).join(" and ")}: ${summary}\n`);
  return 0;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;
if (isMain) {
  const root = process.env.HANGUL_ROUTE_ROOT
    ? resolve(process.env.HANGUL_ROUTE_ROOT)
    : join(dirname(fileURLToPath(import.meta.url)), "..");
  process.exitCode = main(process.argv.slice(2), root);
}
