#!/usr/bin/env node
// F-CURR-002 §5.7, §10 (row CM-48) — "This week in Korea", the week drops.
//
// Reads content/weekly/<monday>.json (one drop per ISO week, `WeekDropSchema` of
// packages/content-schema/src/week-drops/week-drop.ts) and their es / ko overlays,
// content/i18n/<locale>/weekly-<first monday>.json (one file per batch of 13; build-overlays.mjs leaves
// them out of the locale chunks), and writes, under apps/mobile/src/content/__generated__/:
//
//   week-drops-index.ts                 start-loaded: the chunk's hash, the Mondays that have a drop
//                                       (`WEEK_DROP_WEEKS`, so Home knows without loading anything) and
//                                       `loadWeekDrops` (one literal `import()`)
//   week-drop-chunks/week-drops.ts      the chunk: CHUNK_HASH and WEEK_DROPS (`WeekDropEntry`), every ready
//                                       drop with its es and ko text and its notes split into text and
//                                       taught Korean with the F-CNT-002 romanization
//
// Metro emits the chunk as its own content-hashed web bundle, precached by the service worker, so a drop
// opens offline on its week (pwa-postbuild.mjs checks it beside the lesson, story and review-item chunks).
// Both modules are generated, never committed (row CM-6).
//
// The build fails (exit 1) on a drop that is not a `WeekDropSchema` body, on two drops of one week, on an
// item whose romanization is not the converter's, and on an overlay note whose `{ko:}` tokens differ from
// the English note's. Draft drops are left out. The review items of the drops (the `week` memory shard)
// are scripts/build-review-items.mjs's (`weekReviewOccurrences` below).
//
// Usage:
//   node scripts/build-week-drops.mjs            write the modules
//   node scripts/build-week-drops.mjs --check    determinism: fail if a module on disk differs from this run
//   node scripts/build-week-drops.mjs --report   print the chunk's raw and gzip bytes; fail over its budget line
//
// Exit 0 when written / deterministic / within budget, 1 on a content, drift or budget error, 2 on a usage error.
// HANGUL_ROUTE_ROOT overrides the repo root (tests).

import { existsSync, readdirSync, readFileSync } from "node:fs";
import { register } from "node:module";
import { dirname, join, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { gzipSync } from "node:zlib";
import { chunkHash, ContentError } from "./build-lessons.mjs";
import { writeIfChanged } from "./write-if-changed.mjs";

export const GENERATED_HEADER =
  "// GENERATED by scripts/build-week-drops.mjs — do not edit. Source: content/weekly/*.json, content/i18n/<locale>/weekly-*.json (F-CURR-002 §5.7, row CM-48)\n";

export const OUT_DIR = join("apps", "mobile", "src", "content", "__generated__");
export const INDEX_MODULE = "week-drops-index.ts";
export const CHUNK_DIR = "week-drop-chunks";
/** The chunk's module, and the name of its web bundle. */
export const CHUNK_NAME = "week-drops";
const LOCALES = ["es", "ko"];

/**
 * Budget line of the week-drop chunk (F-CURR-002 §10): lazy and precached. Set at CM-48 from its first 13 drops
 * (see the decision record); a year of drops (52) is about four times that, so the batch that crosses the line
 * raises it with its measurement or splits the chunk by batch. The built bundle is held to the same line in
 * apps/mobile/scripts/pwa/lesson-chunks.mjs (`PRECACHE_BUDGET.weekDropsRaw`, `weekDropsGzip`).
 */
export const BUDGET = Object.freeze({ raw: 60_000, gzip: 16_000 });

const SCRIPTS = dirname(fileURLToPath(import.meta.url));
const TOKEN = /\{ko:([^}]*)\}/g;

let loaderRegistered = false;
async function schemaModules() {
  if (!loaderRegistered) {
    register(pathToFileURL(join(SCRIPTS, "ts-loader.mjs")));
    loaderRegistered = true;
  }
  const at = (rel) => pathToFileURL(join(SCRIPTS, "..", "packages", "content-schema", "src", ...rel.split("/"))).href;
  const [drop, rr] = await Promise.all([import(at("week-drops/week-drop.ts")), import(at("romanization/rr.ts"))]);
  return { ...drop, romanize: rr.romanize };
}

function readJson(root, rel) {
  try {
    return JSON.parse(readFileSync(join(root, ...rel.split("/")), "utf8"));
  } catch (error) {
    throw new ContentError(`invalid JSON: ${error.message}`, rel);
  }
}

const listJson = (root, rel) => {
  const dir = join(root, ...rel.split("/"));
  return existsSync(dir) ? readdirSync(dir).filter((n) => n.endsWith(".json")).sort() : [];
};

/** content/weekly/*.json as a content tree (path -> parsed JSON). */
export function weekTree(root) {
  return new Map(listJson(root, "content/weekly").map((name) => [`content/weekly/${name}`, readJson(root, `content/weekly/${name}`)]));
}

/** The weekly overlay entries of each locale: { es: { <week id>: entry }, ko: { ... } }. */
export function weekOverlays(root, m) {
  const out = Object.fromEntries(LOCALES.map((l) => [l, {}]));
  for (const locale of LOCALES) {
    for (const name of listJson(root, `content/i18n/${locale}`).filter((n) => m.WEEK_OVERLAY_NAME_RE.test(n))) {
      const rel = `content/i18n/${locale}/${name}`;
      const json = readJson(root, rel);
      for (const [id, entry] of Object.entries(json?.entries ?? {})) {
        if (!m.WEEK_DROP_ID_RE.test(id)) throw new ContentError(`${id} is not a week drop id (week:<monday>)`, rel);
        out[locale][id] = entry;
      }
    }
  }
  return out;
}

/** A note split into UI text and taught Korean, each token with its F-CNT-002 romanization. */
export function noteParts(text, romanize) {
  const parts = [];
  let at = 0;
  for (const match of text.matchAll(TOKEN)) {
    if (match.index > at) parts.push({ text: text.slice(at, match.index) });
    parts.push({ ko: match[1], romanization: romanize(match[1]).text });
    at = match.index + match[0].length;
  }
  if (at < text.length) parts.push({ text: text.slice(at) });
  return parts;
}

const tokensOf = (text) => Array.from(String(text).matchAll(TOKEN), (t) => t[1]).sort().join(",");

/**
 * Pure: every ready drop of the tree as the chunk holds it, sorted by week. Throws ContentError on a body that is
 * not a drop, two drops of one week, a romanization that is not the converter's, or an overlay note whose tokens
 * differ from the English.
 */
export function buildDrops(tree, overlays, m) {
  const drops = [];
  for (const [rel, json] of [...tree].sort(([a], [b]) => (a < b ? -1 : 1))) {
    const file = m.WEEK_DROP_FILE_RE.exec(rel);
    if (file === null) throw new ContentError("a drop file is content/weekly/<monday>.json", rel);
    const parsed = m.WeekDropSchema.safeParse(json);
    if (!parsed.success) {
      const issue = parsed.error.issues[0];
      throw new ContentError(`${issue.path.join(".") || "(root)"}: ${issue.message}`, rel);
    }
    const drop = parsed.data;
    if (drop.weekOf !== file[1]) throw new ContentError(`the file of the week of ${drop.weekOf} is content/weekly/${drop.weekOf}.json`, rel);
    if (drop.status !== "ready") continue;
    for (const item of drop.items) {
      const want = m.romanize(item.ko).text;
      if (item.romanization !== want) throw new ContentError(`items.${item.id}: the romanization of ${item.ko} is ${want} (F-CNT-002), not ${item.romanization}`, rel);
    }
    const local = (field) => Object.fromEntries(LOCALES.flatMap((l) => (typeof overlays[l][drop.id]?.[field] === "string" ? [[l, overlays[l][drop.id][field]]] : [])));
    const notes = local("note");
    for (const [locale, text] of Object.entries(notes)) {
      if (tokensOf(text) !== tokensOf(drop.noteEn)) {
        throw new ContentError(`the ${locale} note of ${drop.id} needs exactly the tokens of the English note (${tokensOf(drop.noteEn)})`, rel);
      }
    }
    const [first, ...rest] = drop.sources;
    drops.push({
      id: drop.id,
      weekOf: drop.weekOf,
      day: drop.day,
      topic: drop.topic,
      minutes: drop.minutes,
      title: { en: drop.titleEn, ...local("title") },
      note: { en: noteParts(drop.noteEn, m.romanize), ...Object.fromEntries(Object.entries(notes).map(([l, t]) => [l, noteParts(t, m.romanize)])) },
      source: { publisher: first.publisher, title: first.title, more: rest.length },
      items: drop.items.map((item) => ({ id: item.id, ko: item.ko, romanization: item.romanization, gloss: { en: item.en, ...local(`items.${item.id}.gloss`) } })),
    });
  }
  const weeks = drops.map((d) => d.weekOf);
  const twice = weeks.find((w, i) => weeks.indexOf(w) !== i);
  if (twice !== undefined) throw new ContentError(`two drops for the week of ${twice}`, `content/weekly/${twice}.json`);
  return drops;
}

const q = (s) => JSON.stringify(s);

/** Pure: the drops -> the module sources by path under OUT_DIR, and the chunk's hash. */
export function buildModules(drops) {
  const data = `[\n${drops.map((d) => `  ${JSON.stringify(d)},`).join("\n")}\n]`;
  const hash = chunkHash(data);
  const weeks = drops.map((d) => d.weekOf);
  return {
    hash,
    modules: {
      [INDEX_MODULE]:
        GENERATED_HEADER +
        "import type { WeekDropsChunk } from '@hangul-route/content-schema/week-drops';\n\n" +
        "/**\n" +
        " * The week drops (F-CURR-002 §5.7, §10): one content-hashed chunk reached only through the literal `import()`\n" +
        " * below. Metro emits it as its own web bundle (precached by the service worker, loaded on demand) and keeps it in\n" +
        " * the one native bundle. Only these values are in the start bundle.\n" +
        " */\n" +
        // Named so it never reads as a chunk's own `CHUNK_HASH = "<hash>"`: pwa-postbuild.mjs takes that in the start bundle for a chunk pulled in.
        "/** The hash the chunk carries as its CHUNK_HASH. */\n" +
        `export const WEEK_DROPS_HASH = ${q(hash)};\n\n` +
        "/** The Mondays (YYYY-MM-DD) of the ISO weeks that have a drop, in order. */\n" +
        `export const WEEK_DROP_WEEKS: readonly string[] = ${q(weeks)};\n\n` +
        "/** The week-drop chunk; the caller checks its CHUNK_HASH against WEEK_DROPS_HASH. */\n" +
        "export function loadWeekDrops(): Promise<WeekDropsChunk> {\n" +
        `  return import('./${CHUNK_DIR}/${CHUNK_NAME}');\n` +
        "}\n",
      [`${CHUNK_DIR}/${CHUNK_NAME}.ts`]:
        GENERATED_HEADER +
        "import type { WeekDropEntry } from '@hangul-route/content-schema/week-drops';\n\n" +
        "/** The week drops (F-CURR-002 §5.7): reached only through `loadWeekDrops` in ../week-drops-index.ts, never imported statically. */\n" +
        `export const CHUNK_HASH = ${q(hash)};\n\n` +
        `export const WEEK_DROPS: readonly WeekDropEntry[] = ${data};\n`,
    },
  };
}

/** Every drop of the tree under `root`, as the chunk holds them. */
export async function buildFromRoot(root) {
  const m = await schemaModules();
  return buildDrops(weekTree(root), weekOverlays(root, m), m);
}

/** The chunk's name and hash, as pwa-postbuild.mjs checks it beside the lesson, story and review-item chunks. */
export async function readChunkManifest(root) {
  return [{ name: CHUNK_NAME, hash: buildModules(await buildFromRoot(root)).hash }];
}

/** The review-item occurrences of the ready drops (row CM-48), for scripts/build-review-items.mjs. */
export async function weekReviewOccurrences(root, symbols) {
  const at = (name) => pathToFileURL(join(SCRIPTS, "..", "packages", "content-schema", "src", "review-items", name)).href;
  await schemaModules();
  const [{ weekOccurrences }, { weekSourcesOfTree }] = await Promise.all([import(at("extract.ts")), import(at("sources.ts"))]);
  return weekSourcesOfTree(weekTree(root)).flatMap((source) => weekOccurrences(source, symbols));
}

/** Pure: the chunk module's raw and gzip bytes against the budget line (empty problems = within it). */
export function chunkSize(modules) {
  const text = modules[`${CHUNK_DIR}/${CHUNK_NAME}.ts`];
  const raw = Buffer.byteLength(text, "utf8");
  const gzip = gzipSync(text).length;
  const problems = [];
  if (raw > BUDGET.raw) problems.push(`the week-drop chunk is ${raw} B raw, over its ceiling of ${BUDGET.raw} B`);
  if (gzip > BUDGET.gzip) problems.push(`the week-drop chunk is ${gzip} B gzip, over its ceiling of ${BUDGET.gzip} B`);
  return { raw, gzip, problems };
}

const USAGE = "Usage: node scripts/build-week-drops.mjs [--check | --report]";
const relOut = (name) => [...OUT_DIR.split(sep), ...name.split("/")].join("/");

export async function main(argv, root) {
  if (argv.length > 1 || (argv.length === 1 && !["--check", "--report"].includes(argv[0]))) {
    process.stderr.write(`${USAGE}\n`);
    return 2;
  }
  let drops;
  try {
    drops = await buildFromRoot(root);
  } catch (error) {
    if (!(error instanceof ContentError)) throw error;
    process.stdout.write(`::error file=${error.file}::${error.message}\n`);
    return 1;
  }
  const { modules } = buildModules(drops);
  if (argv[0] === "--report") {
    const size = chunkSize(modules);
    process.stdout.write(`Week drops: ${drops.length} drops; chunk ${CHUNK_DIR}/${CHUNK_NAME}.ts ${size.raw} B raw, ${size.gzip} B gzip (ceiling ${BUDGET.raw} B raw, ${BUDGET.gzip} B gzip)\n`);
    for (const p of size.problems) process.stdout.write(`::error file=${relOut(CHUNK_DIR)}::${p}\n`);
    return size.problems.length === 0 ? 0 : 1;
  }
  if (argv[0] === "--check") {
    let drift = 0;
    for (const [name, source] of Object.entries(modules)) {
      const target = join(root, OUT_DIR, ...name.split("/"));
      if (!existsSync(target) || readFileSync(target, "utf8") !== source) {
        drift += 1;
        process.stdout.write(`::error file=${relOut(name)}::generated module is missing or differs from a fresh run of scripts/build-week-drops.mjs (generators must be deterministic); run pnpm generate\n`);
      }
    }
    if (drift > 0) return 1;
    process.stdout.write(`week-drop modules are deterministic (${drops.length} drops)\n`);
    return 0;
  }
  for (const [name, source] of Object.entries(modules)) writeIfChanged(join(root, OUT_DIR, ...name.split("/")), source);
  process.stdout.write(`wrote the week drops: ${drops.length} drops in one chunk\n`);
  return 0;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;
if (isMain) {
  const root = process.env.HANGUL_ROUTE_ROOT ? resolve(process.env.HANGUL_ROUTE_ROOT) : join(SCRIPTS, "..");
  process.exitCode = await main(process.argv.slice(2), root);
}
