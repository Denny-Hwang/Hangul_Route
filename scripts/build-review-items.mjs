#!/usr/bin/env node
// F-CURR-002 §4.2, §9.3 and §10 (row CM-10) — the review-item index.
//
// Merges the three extraction sources into one set of review items with frozen ids:
//
//   1. the shipped lesson cells and ready pack levels: every Discover item and every scored round's
//      answer (build-lessons.mjs `lessonReviewOccurrences`);
//   2. Stage 1, hand-written TypeScript: its frozen symbol, syllable and word table,
//      packages/content-schema/src/review-items/stage1-items.json (a parity test in apps/mobile
//      keeps it equal to the Stage 1 data);
//   3. the shipped stories: the taught words of each story's check rounds (build-stories.mjs
//      `storyReviewOccurrences`);
//
// with the topic words of content/vocab (a topic word keeps its `vocab:` id, so it is one item, not
// two) and the senses of content/vocab/_senses.json (a homograph's sense suffix, `lex:bae~pear`). The
// ids are frozen in packages/content-schema/src/review-items/items-stable-id.json, with its `alias`
// and `retired` lists. It writes, under apps/mobile/src/content/__generated__/:
//
//   review-items-index.ts                  start-loaded: the chunk's hash, the item count, `loadReviewItems`
//                                          (one literal `import()`)
//   review-item-chunks/review-items.ts     the chunk: CHUNK_HASH and REVIEW_ITEM_ROWS (compact rows,
//                                          `ReviewItemRow` of @hangul-route/content-schema/review-items)
//
// Metro emits the chunk as its own web bundle (content-hashed, precached by the service worker,
// loaded on demand), the CM-5 mechanism; pwa-postbuild.mjs checks it with the lesson and story chunks.
// Both modules are generated, never committed (row CM-6): `pnpm generate` runs this after build-lessons.mjs.
//
// The build fails (exit 1) when an edited string would change a frozen id: a frozen id that is no
// longer taught needs an alias (the new key -> the frozen id) or a retirement. A new item that is not
// frozen yet is written with its new id and a warning; the `items-stable-id` rule of validate-content.mjs
// and the snapshot test fail on it until `--freeze` adds it to the snapshot.
//
// Usage:
//   node scripts/build-review-items.mjs            write the modules
//   node scripts/build-review-items.mjs --check    determinism: fail if a module on disk differs from this run
//   node scripts/build-review-items.mjs --report   print the chunk's raw and gzip bytes; fail over its budget line
//   node scripts/build-review-items.mjs --freeze   add the new items' ids to items-stable-id.json (never removes one)
//
// Exit 0 when written / deterministic / within budget, 1 on a content, frozen-id, drift or budget error,
// 2 on a usage error. HANGUL_ROUTE_ROOT overrides the repo root (tests).

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { register } from "node:module";
import { dirname, join, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { gzipSync } from "node:zlib";
import { chunkHash, ContentError, lessonReviewOccurrences } from "./build-lessons.mjs";
import { storyReviewOccurrences } from "./build-stories.mjs";
import { writeIfChanged } from "./write-if-changed.mjs";

export const GENERATED_HEADER =
  "// GENERATED by scripts/build-review-items.mjs — do not edit. Source: content/episodes, content/stories, content/vocab, packages/content-schema/src/review-items/*.json (F-CURR-002 §4.2, row CM-10)\n";

export const OUT_DIR = join("apps", "mobile", "src", "content", "__generated__");
export const INDEX_MODULE = "review-items-index.ts";
export const CHUNK_DIR = "review-item-chunks";
/** The chunk's module, and the name of its web bundle. */
export const CHUNK_NAME = "review-items";
export const SNAPSHOT = "packages/content-schema/src/review-items/items-stable-id.json";
export const STAGE1_TABLE = "packages/content-schema/src/review-items/stage1-items.json";

/**
 * Budget line of the review-item index (F-CURR-002 §10 ceilings table): lazy and precached, so it puts
 * no weight on start-up. The built bundle is held to the same line in apps/mobile/scripts/pwa/lesson-chunks.mjs
 * (`PRECACHE_BUDGET.reviewItemsRaw`, `reviewItemsGzip`). Raising it is a reviewed one-line change with the
 * measured numbers in the PR.
 */
export const BUDGET = Object.freeze({ raw: 150_000, gzip: 30_000 });

const SCRIPTS = dirname(fileURLToPath(import.meta.url));
const relOf = (root, file) => file.slice(root.length + 1).split(sep).join("/");

let loaderRegistered = false;
/** The build-time review-item module of the content-schema package (TypeScript, read through ts-loader.mjs). */
async function reviewItemsModule() {
  if (!loaderRegistered) {
    register(pathToFileURL(join(SCRIPTS, "ts-loader.mjs")));
    loaderRegistered = true;
  }
  const at = (name) => pathToFileURL(join(SCRIPTS, "..", "packages", "content-schema", "src", "review-items", name)).href;
  const [build, stable, item, sources] = await Promise.all([import(at("build.ts")), import(at("stable-ids.ts")), import(at("review-item.ts")), import(at("sources.ts"))]);
  return { ...build, ...stable, ...item, ...sources };
}

function readJsonFile(root, rel) {
  try {
    return JSON.parse(readFileSync(join(root, ...rel.split("/")), "utf8"));
  } catch (error) {
    throw new ContentError(`${existsSync(join(root, ...rel.split("/"))) ? "invalid JSON" : "missing"}: ${error.message}`, rel);
  }
}

/** content/vocab/*.json as a content tree (the topic words and _senses.json; `vocabOfTree` reads them). */
export function vocabTree(root) {
  const dir = join(root, "content", "vocab");
  if (!existsSync(dir)) return new Map();
  return new Map(
    readdirSync(dir)
      .filter((name) => name.endsWith(".json"))
      .sort()
      .map((name) => [`content/vocab/${name}`, readJsonFile(root, `content/vocab/${name}`)]),
  );
}

/** The committed snapshot and Stage 1 table, parsed (a broken one fails the build). */
async function readFrozen(root, m) {
  const parse = (schema, rel) => {
    const result = schema.safeParse(readJsonFile(root, rel));
    if (!result.success) {
      const issue = result.error.issues[0];
      throw new ContentError(`${issue.path.join(".") || "(root)"}: ${issue.message}`, rel);
    }
    return result.data;
  };
  const snapshot = existsSync(join(root, ...SNAPSHOT.split("/"))) ? parse(m.StableIdSnapshotSchema, SNAPSHOT) : m.EMPTY_SNAPSHOT;
  return { snapshot, stage1: parse(m.Stage1TableSchema, STAGE1_TABLE) };
}

/** Every review item of the tree under `root`, with the issues of its frozen ids (see stable-ids.ts). */
export async function buildFromTree(root) {
  const m = await reviewItemsModule();
  const { snapshot, stage1 } = await readFrozen(root, m);
  const { topicWords, senseGroups } = m.vocabOfTree(vocabTree(root));
  const occurrences = [
    ...stage1.occurrences,
    ...(await lessonReviewOccurrences(root, stage1.symbols)),
    ...(await storyReviewOccurrences(root, stage1.symbols)),
  ];
  const result = m.buildReviewItems(occurrences, snapshot, m.vocabIndex(topicWords, senseGroups), stage1.symbols);
  for (const item of result.items) {
    const parsed = m.ReviewItemSchema.safeParse(item);
    if (!parsed.success) {
      const issue = parsed.error.issues[0];
      throw new ContentError(`review item ${item.id}: ${issue.path.join(".")}: ${issue.message}`, SNAPSHOT);
    }
  }
  return { ...result, chunk: m.encodeReviewItems(result.items), retiredRows: result.retired.map(m.encodeRetiredItem), m };
}

const literal = (value) => JSON.stringify(value);
const q = (s) => JSON.stringify(s);

/**
 * Pure: the chunk's tables and rows (`encodeReviewItems`) and the retired items' rows
 * (`encodeRetiredItem`, sorted by id) -> the module sources by path under OUT_DIR, and the chunk's hash.
 */
export function buildModules({ tables, rows }, retired = []) {
  const data = `[\n${rows.map((row) => `  ${literal(row)},`).join("\n")}\n]`;
  const shared = literal(tables);
  const retiredRows = literal([...retired].sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0)));
  const hash = chunkHash(shared + data + retiredRows);
  const modules = {
    [INDEX_MODULE]:
      GENERATED_HEADER +
      "import type { ReviewItemsChunk } from '@hangul-route/content-schema/review-items';\n\n" +
      "/**\n" +
      " * The review-item index (F-CURR-002 §4.2, §10): every taught unit with its frozen id, in one\n" +
      " * content-hashed chunk reached only through the literal `import()` below. Metro emits it as its\n" +
      " * own web bundle (precached by the service worker, loaded on demand) and keeps it in the one\n" +
      " * native bundle. Nothing reads it before the review engine (row CM-13).\n" +
      " */\n" +
      // Named so it never reads as a chunk's own `CHUNK_HASH = "<hash>"`: pwa-postbuild.mjs takes that in the start bundle for a chunk pulled in.
      "/** The hash the chunk carries as its CHUNK_HASH. */\n" +
      `export const REVIEW_ITEMS_HASH = ${q(hash)};\n\n` +
      `/** How many items the chunk holds. */\n` +
      `export const REVIEW_ITEM_COUNT = ${rows.length};\n\n` +
      "/** The review-item chunk; the caller checks its CHUNK_HASH against REVIEW_ITEMS_HASH. */\n" +
      "export function loadReviewItems(): Promise<ReviewItemsChunk> {\n" +
      `  return import('./${CHUNK_DIR}/${CHUNK_NAME}');\n` +
      "}\n",
    [`${CHUNK_DIR}/${CHUNK_NAME}.ts`]:
      GENERATED_HEADER +
      "import type { RetiredItemRow, ReviewItemRow, ReviewItemTables } from '@hangul-route/content-schema/review-items';\n\n" +
      "/** The review items (F-CURR-002 §4.2): reached only through `loadReviewItems` in ../review-items-index.ts, never imported statically. */\n" +
      `export const CHUNK_HASH = ${q(hash)};\n\n` +
      "/** The cells and homes the rows name by index. */\n" +
      `export const REVIEW_ITEM_TABLES: ReviewItemTables = ${shared};\n\n` +
      "/** [id, ko, romanization, en, glossKey, home, meta, cells, formats, homophoneOf, reply, picture, asked] (`decodeReviewItems`). */\n" +
      `export const REVIEW_ITEM_ROWS: readonly ReviewItemRow[] = ${data};\n\n` +
      "/** The retired items of items-stable-id.json, [id, ko, romanization] (`decodeRetiredItem`): never selected for review, out of every mastery denominator, their learner state kept and named in reports. */\n" +
      `export const REVIEW_RETIRED: readonly RetiredItemRow[] = ${retiredRows};\n`,
  };
  return { modules, hash };
}

/** The chunk's name and hash, as pwa-postbuild.mjs checks it beside the lesson and story chunks. */
export async function readChunkManifest(root) {
  const { chunk, retiredRows } = await buildFromTree(root);
  return [{ name: CHUNK_NAME, hash: buildModules(chunk, retiredRows).hash }];
}

/** Pure: the chunk module's raw and gzip bytes against the budget line (empty problems = within it). */
export function chunkSize(modules) {
  const text = modules[`${CHUNK_DIR}/${CHUNK_NAME}.ts`];
  const raw = Buffer.byteLength(text, "utf8");
  const gzip = gzipSync(text).length;
  const problems = [];
  if (raw > BUDGET.raw) problems.push(`the review-item chunk is ${raw} B raw, over its ceiling of ${BUDGET.raw} B`);
  if (gzip > BUDGET.gzip) problems.push(`the review-item chunk is ${gzip} B gzip, over its ceiling of ${BUDGET.gzip} B`);
  return { raw, gzip, problems };
}

/** Issues that stop the build: everything but an item that is new and not frozen yet. */
export const isBlocking = (issue) => issue.code !== "not-frozen";

/** Files under the chunk folder that this run does not write. */
function staleChunks(root, modules) {
  const dir = join(root, OUT_DIR, CHUNK_DIR);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith(".ts"))
    .map((f) => `${CHUNK_DIR}/${f}`)
    .filter((name) => modules[name] === undefined);
}

const USAGE = "Usage: node scripts/build-review-items.mjs [--check | --report | --freeze]";

export async function main(argv, root) {
  if (argv.length > 1 || (argv.length === 1 && !["--check", "--report", "--freeze"].includes(argv[0]))) {
    process.stderr.write(`${USAGE}\n`);
    return 2;
  }
  const mode = argv[0];
  let built;
  try {
    built = await buildFromTree(root);
  } catch (error) {
    if (!(error instanceof ContentError)) throw error;
    process.stdout.write(`::error file=${error.file}::${error.message}\n`);
    return 1;
  }
  const blocking = built.issues.filter(isBlocking);
  for (const issue of blocking) process.stdout.write(`::error file=${SNAPSHOT}::items-stable-id: ${issue.message}${issue.at ? ` (${issue.at})` : ""}\n`);
  if (blocking.length > 0) return 1;

  if (mode === "--freeze") {
    writeFileSync(join(root, ...SNAPSHOT.split("/")), built.m.serializeSnapshot(built.frozen));
    const added = built.issues.filter((i) => i.code === "not-frozen").length;
    process.stdout.write(`froze ${added} new review item ids in ${SNAPSHOT} (${Object.keys(built.frozen.ids).length} frozen in all)\n`);
    return 0;
  }
  for (const issue of built.issues) process.stdout.write(`::warning file=${SNAPSHOT}::items-stable-id: ${issue.message}\n`);

  const { modules } = buildModules(built.chunk, built.retiredRows);
  if (mode === "--report") {
    const size = chunkSize(modules);
    process.stdout.write(`Review items: ${built.chunk.rows.length} items; chunk ${CHUNK_DIR}/${CHUNK_NAME}.ts ${size.raw} B raw, ${size.gzip} B gzip (ceiling ${BUDGET.raw} B raw, ${BUDGET.gzip} B gzip)\n`);
    for (const p of size.problems) process.stdout.write(`::error file=${OUT_DIR.split(sep).join("/")}::${p}\n`);
    return size.problems.length === 0 ? 0 : 1;
  }
  const stale = staleChunks(root, modules);
  if (mode === "--check") {
    let drift = 0;
    for (const [name, source] of Object.entries(modules)) {
      const target = join(root, OUT_DIR, name);
      if (!existsSync(target) || readFileSync(target, "utf8") !== source) {
        drift += 1;
        process.stdout.write(`::error file=${relOf(root, target)}::generated module is missing or differs from a fresh run of scripts/build-review-items.mjs (generators must be deterministic); run pnpm generate\n`);
      }
    }
    for (const name of stale) {
      drift += 1;
      process.stdout.write(`::error file=${OUT_DIR.split(sep).join("/")}/${name}::generated review-item module is no longer built; run pnpm generate (it removes it)\n`);
    }
    if (drift > 0) return 1;
    process.stdout.write(`review-item modules are deterministic (${built.chunk.rows.length} items)\n`);
    return 0;
  }
  mkdirSync(join(root, OUT_DIR, CHUNK_DIR), { recursive: true });
  for (const name of stale) rmSync(join(root, OUT_DIR, name));
  for (const [name, source] of Object.entries(modules)) writeIfChanged(join(root, OUT_DIR, name), source);
  process.stdout.write(`wrote the review-item index: ${built.chunk.rows.length} items in one chunk\n`);
  return 0;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;
if (isMain) {
  const root = process.env.HANGUL_ROUTE_ROOT ? resolve(process.env.HANGUL_ROUTE_ROOT) : join(SCRIPTS, "..");
  process.exitCode = await main(process.argv.slice(2), root);
}
