#!/usr/bin/env node
// F-VOC-001 §3.7 — vocabulary bundle generator (PR V-2a).
//
// Reads content/vocab/<topic>.json (one VocabTopicFile each; _senses.json is the
// sense registry, not a topic) and the glosses of content/i18n/{es,ko}/vocab-*.json,
// and writes two checked-in modules:
//
//   apps/mobile/src/content/__generated__/vocab.ts
//       VOCAB_TOPICS  VocabTopic[]         ordered by `order`
//       VOCAB_ITEMS   RuntimeVocabItem[]   topic order, then file order, `glosses` assembled,
//                                          `audioRef` derived from the id when the file has none
//       VOCAB_SENSES  sense groups of content/vocab/_senses.json
//   apps/web/src/data/vocab-catalog.ts
//       VOCAB_CATALOG id, ko, romanization, en, primary topic, visual, glosses
//                     (console roster in its UI language, WordArt sheet)
//
// This is a shaper: it applies the schema defaults (`pos`, `fixedOrder`), drops
// unknown fields and fails on JSON it cannot read or a field it must emit. Semantic
// validation (romanization, duplicates, senses, banned words) is the job of
// packages/content-schema/src/__tests__/vocab-content.test.ts. Draft topics are
// bundled on purpose: the picker hides them (spec V12). The literals are typed by
// contextual typing, so `tsc --noEmit` is a second gate.
//
// Usage:
//   node scripts/build-vocab.mjs            write both modules
//   node scripts/build-vocab.mjs --check    fail if a checked-in module differs (CI)
//
// Dependency-free Node (same family as build-stories.mjs). Exit 0 when written / in
// sync, 1 on a content or drift error, 2 on a usage error. HANGUL_ROUTE_ROOT
// overrides the repo root (tests).

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const GENERATED_HEADER =
  "// GENERATED by scripts/build-vocab.mjs — do not edit. Source: content/vocab/*.json, content/i18n/{es,ko}/vocab-*.json\n";

const OVERLAY_LOCALES = Object.freeze(["es", "ko"]);

class ContentError extends Error {}

// ---- shaping (pure) --------------------------------------------------------------

function isObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function str(obj, field, where) {
  const value = obj[field];
  if (typeof value !== "string" || value.length === 0) {
    throw new ContentError(`${where}: ${field} must be a non-empty string`);
  }
  return value;
}

function optStr(obj, field, where) {
  const value = obj[field];
  if (value === undefined) return undefined;
  if (typeof value !== "string") throw new ContentError(`${where}: ${field} must be a string`);
  return value;
}

function num(obj, field, where) {
  if (typeof obj[field] !== "number") throw new ContentError(`${where}: ${field} must be a number`);
  return obj[field];
}

function shapeTopic(topic, where) {
  if (!isObject(topic)) throw new ContentError(`${where}: topic must be an object`);
  const titleKo = topic.titleKo;
  if (!isObject(titleKo)) throw new ContentError(`${where}: titleKo must be an object`);
  const fixedOrder = topic.fixedOrder === undefined ? false : topic.fixedOrder;
  if (typeof fixedOrder !== "boolean") throw new ContentError(`${where}: fixedOrder must be a boolean`);
  return {
    id: str(topic, "id", where),
    key: str(topic, "key", where),
    order: num(topic, "order", where),
    titleEn: str(topic, "titleEn", where),
    titleKo,
    blurbEn: str(topic, "blurbEn", where),
    hoyaIntroEn: str(topic, "hoyaIntroEn", where),
    tint: str(topic, "tint", where),
    coverItemId: str(topic, "coverItemId", where),
    status: str(topic, "status", where),
    fixedOrder,
  };
}

function glossesOf(id, en, overlays) {
  const glosses = { en };
  for (const locale of OVERLAY_LOCALES) {
    const value = overlays[locale]?.get(id);
    if (value !== undefined) glosses[locale] = value;
  }
  return glosses;
}

/**
 * The clip path of a vocabulary item: `audio/vocab/<id without vocab:>.mp3`, the only value
 * `VocabItemSchema` allows (F-AUDIO-004 §3.10). Every item carries it, so the recording list
 * (apps/mobile/scripts/audio) and the clip map cover every word, and a recording that lands
 * later plays on the learner cards and the presenter's word slides with no content edit; until
 * then the controller finds no bundled clip and the device voice says the word.
 */
export function vocabAudioRef(id) {
  return `audio/vocab/${id.slice("vocab:".length)}.mp3`;
}

function shapeItem(item, overlays, where) {
  if (!isObject(item)) throw new ContentError(`${where}: an item must be an object`);
  const at = `${where} ${typeof item.id === "string" ? item.id : "(item without id)"}`;
  const out = {
    id: str(item, "id", at),
    ko: str(item, "ko", at),
    romanization: str(item, "romanization", at),
    en: str(item, "en", at),
    pos: optStr(item, "pos", at) ?? "noun",
  };
  if (!Array.isArray(item.topics)) throw new ContentError(`${at}: topics must be an array`);
  out.topics = item.topics;
  out.level = num(item, "level", at);
  out.visual = str(item, "visual", at);
  for (const field of ["senseNote", "senseGroup", "spokenKo"]) {
    const value = optStr(item, field, at);
    if (value !== undefined) out[field] = value;
  }
  out.audioRef = optStr(item, "audioRef", at) ?? vocabAudioRef(out.id);
  if (item.example !== undefined) out.example = item.example;
  out.glosses = glossesOf(out.id, out.en, overlays);
  return out;
}

/**
 * Pure: parsed inputs to the shaped model.
 *   topicFiles  parsed content/vocab/<topic>.json objects
 *   senses      parsed _senses.json (or null when the file does not exist)
 *   overlays    { es: Map<id, gloss>, ko: Map<id, gloss> }
 */
export function buildVocab({ topicFiles, senses, overlays }) {
  const shaped = topicFiles.map((file) => {
    const where = isObject(file?.topic) && typeof file.topic.key === "string" ? file.topic.key : "(topic file)";
    if (!isObject(file)) throw new ContentError(`${where}: a topic file must hold one JSON object`);
    const topic = shapeTopic(file.topic, where);
    if (!Array.isArray(file.items)) throw new ContentError(`${where}: items must be an array`);
    return { topic, items: file.items.map((raw) => shapeItem(raw, overlays, where)) };
  });
  shaped.sort((a, b) => a.topic.order - b.topic.order || (a.topic.key < b.topic.key ? -1 : 1));
  return {
    topics: shaped.map((s) => s.topic),
    items: shaped.flatMap((s) => s.items),
    senses: senses ? senses.groups : [],
  };
}

function literal(value) {
  return JSON.stringify(value, null, 2);
}

export function renderMobile({ topics, items, senses }) {
  return (
    GENERATED_HEADER +
    "import type { RuntimeVocabItem, VocabSensesFile, VocabTopic } from '@hangul-route/content-schema';\n\n" +
    `export const VOCAB_TOPICS: readonly VocabTopic[] = ${literal(topics)};\n\n` +
    `export const VOCAB_ITEMS: readonly RuntimeVocabItem[] = ${literal(items)};\n\n` +
    `export const VOCAB_SENSES: VocabSensesFile['groups'] = ${literal(senses)};\n`
  );
}

export function renderWeb({ items }) {
  const catalog = items.map((i) => ({
    id: i.id,
    ko: i.ko,
    romanization: i.romanization,
    en: i.en,
    topic: i.topics[0],
    visual: i.visual,
    glosses: i.glosses,
  }));
  return (
    GENERATED_HEADER +
    "export interface VocabCatalogEntry {\n" +
    "  id: string;\n  ko: string;\n  romanization: string;\n  en: string;\n  topic: string;\n  visual: string;\n" +
    "  /** The gloss in each UI language that has one; `en` always. */\n" +
    "  glosses: { en: string; es?: string; ko?: string };\n}\n\n" +
    `export const VOCAB_CATALOG: readonly VocabCatalogEntry[] = ${literal(catalog)};\n`
  );
}

// ---- file system and CLI ---------------------------------------------------------

function relOf(root, file) {
  return relative(root, file).split(sep).join("/");
}

function readJson(root, file) {
  const rel = relOf(root, file);
  try {
    return JSON.parse(readFileSync(file, "utf8"));
  } catch (error) {
    throw new ContentError(`::error file=${rel}::not valid JSON: ${error.message}`);
  }
}

function annotate(root, file, run) {
  try {
    return run();
  } catch (error) {
    if (error instanceof ContentError && !error.message.startsWith("::error")) {
      throw new ContentError(`::error file=${relOf(root, file)}::${error.message}`);
    }
    throw error;
  }
}

function listJson(dir, accept) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith(".json") && accept(e.name))
    .map((e) => e.name)
    .sort();
}

function readTopicFiles(root) {
  const dir = join(root, "content", "vocab");
  return listJson(dir, (name) => !name.startsWith("_")).map((name) => {
    const file = join(dir, name);
    const json = readJson(root, file);
    if (!isObject(json)) {
      throw new ContentError(`::error file=${relOf(root, file)}::a topic file must hold one JSON object`);
    }
    return { file, json };
  });
}

function readSenses(root) {
  const file = join(root, "content", "vocab", "_senses.json");
  if (!existsSync(file)) return null;
  const json = readJson(root, file);
  if (!isObject(json) || !Array.isArray(json.groups)) {
    throw new ContentError(`::error file=${relOf(root, file)}::_senses.json needs a groups array`);
  }
  return json;
}

function readOverlays(root) {
  const overlays = {};
  for (const locale of OVERLAY_LOCALES) {
    const glosses = new Map();
    const dir = join(root, "content", "i18n", locale);
    for (const name of listJson(dir, (n) => n.startsWith("vocab-"))) {
      const file = join(dir, name);
      const json = readJson(root, file);
      if (!isObject(json) || !isObject(json.entries)) {
        throw new ContentError(`::error file=${relOf(root, file)}::an overlay needs an entries object`);
      }
      for (const [id, entry] of Object.entries(json.entries)) {
        if (id.startsWith("vocab:") && isObject(entry) && typeof entry.gloss === "string") {
          glosses.set(id, entry.gloss);
        }
      }
    }
    overlays[locale] = glosses;
  }
  return overlays;
}

function loadModel(root) {
  const topicFiles = readTopicFiles(root);
  const senses = readSenses(root);
  const overlays = readOverlays(root);
  const parsed = topicFiles.map(({ file, json }) =>
    annotate(root, file, () => {
      // shape-check each file on its own so the annotation names it
      buildVocab({ topicFiles: [json], senses: null, overlays });
      return json;
    })
  );
  return buildVocab({ topicFiles: parsed, senses, overlays });
}

function firstDifference(expected, actual) {
  const a = expected.split("\n");
  const b = actual.split("\n");
  const n = Math.max(a.length, b.length);
  for (let i = 0; i < n; i += 1) {
    if (a[i] !== b[i]) {
      return `line ${i + 1}: expected ${JSON.stringify(a[i] ?? "(end of file)")}, found ${JSON.stringify(b[i] ?? "(end of file)")}`;
    }
  }
  return "no difference";
}

const USAGE = "Usage: node scripts/build-vocab.mjs [--check]";

export function main(argv, root) {
  let check = false;
  for (const arg of argv) {
    if (arg === "--check") check = true;
    else {
      process.stderr.write(`unknown argument ${arg}\n${USAGE}\n`);
      return 2;
    }
  }

  let model;
  try {
    model = loadModel(root);
  } catch (error) {
    process.stdout.write(`${error instanceof ContentError ? error.message : `::error::${error.message}`}\n`);
    return 1;
  }

  const outputs = [
    { file: join(root, "apps", "mobile", "src", "content", "__generated__", "vocab.ts"), source: renderMobile(model) },
    { file: join(root, "apps", "web", "src", "data", "vocab-catalog.ts"), source: renderWeb(model) },
  ];
  const summary = `${model.topics.length} topics, ${model.items.length} items`;

  if (check) {
    let failed = false;
    for (const { file, source } of outputs) {
      const rel = relOf(root, file);
      if (!existsSync(file)) {
        process.stdout.write(`::error file=${rel}::generated vocabulary module is missing; run node scripts/build-vocab.mjs\n`);
        failed = true;
      } else {
        const found = readFileSync(file, "utf8");
        if (found !== source) {
          process.stdout.write(
            `::error file=${rel}::generated vocabulary module is out of date with content/vocab (${firstDifference(source, found)}); run node scripts/build-vocab.mjs and commit the result\n`
          );
          failed = true;
        }
      }
    }
    if (!failed) process.stdout.write(`vocabulary modules are up to date (${summary})\n`);
    return failed ? 1 : 0;
  }

  for (const { file, source } of outputs) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, source);
  }
  process.stdout.write(`wrote ${outputs.map((o) => relOf(root, o.file)).join(" and ")}: ${summary}\n`);
  return 0;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;
if (isMain) {
  const root = process.env.HANGUL_ROUTE_ROOT
    ? resolve(process.env.HANGUL_ROUTE_ROOT)
    : join(dirname(fileURLToPath(import.meta.url)), "..");
  process.exitCode = main(process.argv.slice(2), root);
}
